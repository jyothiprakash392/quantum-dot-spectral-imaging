function config = qdDownconversionConfig(varargin)
%QDDOWNCONVERSIONCONFIG Configuration for the passive UV-to-NIR converter.
%   CONFIG = QDDOWNCONVERSIONCONFIG creates a voltage-commanded electronic
%   selector containing six fixed-emission quantum-dot channels. An ADC and
%   voltage-window decoder choose a channel through solid-state optical
%   gates; no rotor or other mechanical motion is required. The selector
%   voltage does not make one quantum-dot film continuously tune from the
%   visible to the near infrared.
%
%   The default input is a 280-420 nm photon spectrum. The selectable
%   output bands span 470-1410 nm. A dichroic detector model routes the
%   visible/NIR-I portion to a silicon CCD and the longer-wave portion to
%   an InGaAs array.
%
%   All efficiency and spectral-response values are illustrative device-
%   level parameters until replaced by measured calibration data.

scalarPositive = @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&& ...
    isfinite(x)&&x>0;
unitIntervalVector = @(x)isnumeric(x)&&isvector(x)&&isreal(x)&& ...
    all(isfinite(x(:)))&&all(x(:)>=0)&&all(x(:)<=1);
vectorIncreasing = @(x)isnumeric(x)&&isvector(x)&&isreal(x)&& ...
    all(isfinite(x(:)))&&numel(x)>=3&&all(diff(x(:))>0);
textScalar = @(x)ischar(x)||(isstring(x)&&isscalar(x));

defaultMaterials = { ...
    'CdS/ZnS blue film'; ...
    'InP/ZnSe/ZnS green film'; ...
    'InP/ZnSe/ZnS red film'; ...
    'InAs/InP/ZnSe/ZnS NIR-I film'; ...
    'InAs/ZnSe NIR film'; ...
    'InAs/ZnSe extended-NIR film'};

parser = inputParser;
parser.FunctionName = 'qdDownconversionConfig';
addParameter(parser,'InputWavelength_nm',(280:4:420).',vectorIncreasing);
addParameter(parser,'OutputWavelength_nm',(420:5:1800).',vectorIncreasing);
addParameter(parser,'SelectorVoltages_V',(0.3:0.5:2.8).',vectorIncreasing);
addParameter(parser,'EmitterCenter_nm',[470 535 625 905 1275 1410].', ...
    vectorIncreasing);
addParameter(parser,'EmitterFWHM_eV',[0.13 0.12 0.10 0.124 0.177 0.165].', ...
    @(x)isnumeric(x)&&isvector(x)&&isreal(x)&&all(isfinite(x(:)))&& ...
    all(x(:)>0));
addParameter(parser,'AbsorptionCenter_nm',[330 338 346 354 362 370].', ...
    vectorIncreasing);
addParameter(parser,'AbsorptionFWHM_nm',200*ones(6,1), ...
    @(x)isnumeric(x)&&isvector(x)&&isreal(x)&&all(isfinite(x(:)))&& ...
    all(x(:)>0));
addParameter(parser,'PeakAbsorptance',[0.78 0.80 0.82 0.76 0.70 0.62].', ...
    unitIntervalVector);
addParameter(parser,'FilmPhotoluminescenceYield', ...
    [0.55 0.62 0.60 0.52 0.30 0.17].',unitIntervalVector);
addParameter(parser,'FilmExtractionEfficiency', ...
    [0.72 0.72 0.70 0.66 0.58 0.52].',unitIntervalVector);
addParameter(parser,'MaterialNames',defaultMaterials, ...
    @(x)iscellstr(x)||isstring(x));
addParameter(parser,'SelectorMode','nearest_channel', ...
    @(x)textScalar(x)&&any(strcmpi(char(x), ...
    {'nearest_channel','nearest_detent','adjacent_channel_blend', ...
    'adjacent_crossfade'})));
addParameter(parser,'CrossfadeWidth_V',0.08,scalarPositive);
addParameter(parser,'SelectorADCResolution_bits',12, ...
    @(x)scalarPositive(x)&&x==fix(x)&&x>=2&&x<=24);
addParameter(parser,'SelectorADCReferenceVoltage_V',3.3,scalarPositive);
addParameter(parser,'SelectorHysteresis_V',0.02, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'QCSEPeakShift_nm',0, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'SpectrometerPixelCount',12, ...
    @(x)scalarPositive(x)&&x==fix(x)&&x>=4&&x<=64);
addParameter(parser,'SpectrometerBiasVoltages_V',linspace(0,1.0,5).', ...
    vectorIncreasing);
addParameter(parser,'FilterResponseFWHM_nm',6,scalarPositive);
addParameter(parser,'FilterShiftRange_nm',8, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'ReconstructionRegularization',0.008, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'ReconstructionMaxIterations',3000, ...
    @(x)scalarPositive(x)&&x==fix(x));
addParameter(parser,'OpticalTransmission',0.80, ...
    @(x)unitIntervalVector(x)&&isscalar(x));
addParameter(parser,'DetectorFillFactor',0.90, ...
    @(x)unitIntervalVector(x)&&isscalar(x));
addParameter(parser,'SiliconQuantumEfficiencyPeak',0.88, ...
    @(x)unitIntervalVector(x)&&isscalar(x));
addParameter(parser,'InGaAsQuantumEfficiencyPeak',0.82, ...
    @(x)unitIntervalVector(x)&&isscalar(x));
addParameter(parser,'DichroicCrossover_nm',960,scalarPositive);
addParameter(parser,'DichroicTransitionWidth_nm',22,scalarPositive);
addParameter(parser,'SiliconReadNoiseElectronsRMS',1.7, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'InGaAsReadNoiseElectronsRMS',8.0, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'SiliconDarkCurrent_ePerSecond',0.25, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'InGaAsDarkCurrent_ePerSecond',45, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'ExposureTime_s',0.020,scalarPositive);
addParameter(parser,'FullWellElectrons',8e4,scalarPositive);
addParameter(parser,'DefaultSelectorVoltage_V',1.8, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x));
addParameter(parser,'RandomSeed',271828, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&& ...
    x==fix(x)&&x>=0);
parse(parser,varargin{:});
options = parser.Results;

selectorVoltages_V = options.SelectorVoltages_V(:);
emitterCenter_nm = options.EmitterCenter_nm(:);
emitterFWHM_eV = options.EmitterFWHM_eV(:);
absorptionCenter_nm = options.AbsorptionCenter_nm(:);
absorptionFWHM_nm = options.AbsorptionFWHM_nm(:);
peakAbsorptance = options.PeakAbsorptance(:);
plYield = options.FilmPhotoluminescenceYield(:);
extraction = options.FilmExtractionEfficiency(:);
materialNames = cellstr(options.MaterialNames(:));
filmCount = numel(selectorVoltages_V);

lengths = [numel(emitterCenter_nm),numel(emitterFWHM_eV), ...
    numel(absorptionCenter_nm),numel(absorptionFWHM_nm), ...
    numel(peakAbsorptance),numel(plYield),numel(extraction), ...
    numel(materialNames)];
if any(lengths~=filmCount)
    error('VirtualQD:DownconversionConfig', ...
        'Every film property must contain one value per selector channel.');
end
if any(emitterCenter_nm<=max(options.InputWavelength_nm))
    error('VirtualQD:DownconversionEnergy', ...
        ['Every passive down-conversion emission center must be longer ' ...
        'than the complete configured input band.']);
end
if emitterCenter_nm(1)<options.OutputWavelength_nm(1) || ...
        emitterCenter_nm(end)>options.OutputWavelength_nm(end)
    error('VirtualQD:DownconversionBand', ...
        'Emitter centers must lie inside the configured output grid.');
end
if options.DefaultSelectorVoltage_V<selectorVoltages_V(1) || ...
        options.DefaultSelectorVoltage_V>selectorVoltages_V(end)
    error('VirtualQD:SelectorVoltage', ...
        'Default selector voltage must lie within the channel-voltage range.');
end
if options.SelectorADCReferenceVoltage_V<selectorVoltages_V(end)
    error('VirtualQD:SelectorADCReference', ...
        'Selector ADC reference voltage must cover every channel voltage.');
end
if options.SelectorHysteresis_V>=min(diff(selectorVoltages_V))
    error('VirtualQD:SelectorHysteresis', ...
        'Selector hysteresis must be smaller than the channel spacing.');
end

selectorMode = lower(char(options.SelectorMode));
if strcmp(selectorMode,'nearest_detent')
    % Backward-compatible spelling used by the earlier rotary UI version.
    selectorMode = 'nearest_channel';
elseif strcmp(selectorMode,'adjacent_crossfade')
    selectorMode = 'adjacent_channel_blend';
end

config = struct();
config.schemaVersion = '1.2.0';
config.systemName = 'Voltage-Selected QD UV-to-NIR Downconverter';
config.inputWavelength_nm = options.InputWavelength_nm(:);
config.outputWavelength_nm = options.OutputWavelength_nm(:);
config.inputDefinition = ['photons per UV wavelength bin per illuminated ' ...
    'film area and detector exposure'];
% detentVoltage_V is a deprecated compatibility alias for saved scripts.
config.selector = struct( ...
    'commandName','electronic selector voltage', ...
    'channelVoltage_V',selectorVoltages_V, ...
    'detentVoltage_V',selectorVoltages_V, ...
    'minimumVoltage_V',selectorVoltages_V(1), ...
    'maximumVoltage_V',selectorVoltages_V(end), ...
    'defaultVoltage_V',options.DefaultSelectorVoltage_V, ...
    'thresholdVoltage_V',0.5*(selectorVoltages_V(1:end-1)+ ...
        selectorVoltages_V(2:end)), ...
    'mode',selectorMode, ...
    'crossfadeWidth_V',options.CrossfadeWidth_V, ...
    'hysteresis_V',options.SelectorHysteresis_V, ...
    'adc',struct( ...
        'resolution_bits',options.SelectorADCResolution_bits, ...
        'referenceVoltage_V',options.SelectorADCReferenceVoltage_V, ...
        'leastSignificantBit_V',options.SelectorADCReferenceVoltage_V/ ...
            (2^options.SelectorADCResolution_bits-1)), ...
    'logicOutput','one-hot 1-of-6 solid-state gate command', ...
    'hardwareArchitecture',['ADC plus voltage-window decoder driving an ' ...
        'analog multiplexer, electronic shutter, or electro-optic gate bank'], ...
    'physicalMeaning',['voltage commands a solid-state channel selector ' ...
        'that routes excitation to one fixed-emission QD film'], ...
    'doesNotMean',['a single passive QD film continuously tunes from UV ' ...
        'to NIR as voltage changes']);
config.filmCount = filmCount;
config.film = struct( ...
    'material',{materialNames}, ...
    'emissionCenter_nm',emitterCenter_nm, ...
    'emissionFWHM_eV',emitterFWHM_eV, ...
    'absorptionCenter_nm',absorptionCenter_nm, ...
    'absorptionFWHM_nm',absorptionFWHM_nm, ...
    'peakAbsorptance',peakAbsorptance, ...
    'photoluminescenceQuantumYield',plYield, ...
    'extractionEfficiency',extraction, ...
    'qcsePeakShift_nm',options.QCSEPeakShift_nm);
spectrometerBiasVoltages_V = options.SpectrometerBiasVoltages_V(:);
config.spectrometer = struct( ...
    'pixelCount',options.SpectrometerPixelCount, ...
    'biasVoltages_V',spectrometerBiasVoltages_V, ...
    'biasCount',numel(spectrometerBiasVoltages_V), ...
    'measurementCount',options.SpectrometerPixelCount* ...
        numel(spectrometerBiasVoltages_V), ...
    'filterResponseFWHM_nm',options.FilterResponseFWHM_nm, ...
    'filterShiftRange_nm',options.FilterShiftRange_nm, ...
    'architecture',['wavelength-selective UV filter pixels measured at ' ...
        'sequential electro-absorption bias states; the detector retains ' ...
        'spatial channel identity'], ...
    'inputDefinition',['photons per wavelength bin, per spatial filter ' ...
        'pixel, per sequential filter-bias exposure'], ...
    'reconstructionMethod','nonnegative projected-FISTA Tikhonov', ...
    'reconstructionRegularization',options.ReconstructionRegularization, ...
    'reconstructionMaxIterations',options.ReconstructionMaxIterations);
config.detector = struct( ...
    'architecture','dichroic silicon CCD plus InGaAs spectral array', ...
    'opticalTransmission',options.OpticalTransmission, ...
    'fillFactor',options.DetectorFillFactor, ...
    'siliconQuantumEfficiencyPeak',options.SiliconQuantumEfficiencyPeak, ...
    'ingaasQuantumEfficiencyPeak',options.InGaAsQuantumEfficiencyPeak, ...
    'dichroicCrossover_nm',options.DichroicCrossover_nm, ...
    'dichroicTransitionWidth_nm',options.DichroicTransitionWidth_nm, ...
    'siliconReadNoiseElectronsRMS', ...
        options.SiliconReadNoiseElectronsRMS, ...
    'ingaasReadNoiseElectronsRMS', ...
        options.InGaAsReadNoiseElectronsRMS, ...
    'siliconDarkCurrent_ePerSecond', ...
        options.SiliconDarkCurrent_ePerSecond, ...
    'ingaasDarkCurrent_ePerSecond', ...
        options.InGaAsDarkCurrent_ePerSecond, ...
    'exposureTime_s',options.ExposureTime_s, ...
    'fullWellElectrons',options.FullWellElectrons);
config.randomSeed = options.RandomSeed;
config.calibration = struct( ...
    'mode','physics-constrained synthetic film bank', ...
    'label','UNMEASURED DEFAULT - replace film and detector curves', ...
    'filmSpectraMeasured',false, ...
    'detectorResponseMeasured',false);
config.validity = struct( ...
    'passiveOnePhotonDownconversion',true, ...
    'selectorVoltageIsElectronicCommand',true, ...
    'selectorVoltageIsActuatorCommand',true, ...
    'mechanicalMotionRequired',false, ...
    'singleFilmWideVoltageTuningClaim',false, ...
    'quantitativeHardwarePrediction',false, ...
    'requiresInGaAsAboveSiliconCutoff',true, ...
    'restrictedMaterialWarning',['material names are design placeholders; ' ...
        'fabrication requires material-specific toxicity, encapsulation, ' ...
        'optical-exposure, and disposal review']);
end
