function v = qdMaterialVector(materialID)
%QDMATERIALVECTOR Numeric, code-generation-safe material parameter record.
%   Material 1 is the mechanistic CdSe/ZnS baseline. Material 5 is a
%   room-temperature CdSe-core accuracy preset fitted to the mean of three
%   published sizing curves over 3-8 nm diameter; its parameters are
%   effective fit parameters rather than literal bulk constants.
%
% Vector layout:
% [Eg0 alpha beta me mh epsIn nOut aGap Ve Vh meBarrier mhBarrier ...
%  krRef knrRef trapSigma augerRef sigma350 loPhonon aB lattice ...
%  stokes confidence trapDepth trapDecay]

id = round(materialID);
if ~isfinite(materialID) || abs(materialID-id) > 1.0e-12 || ...
        id < 1 || id > 5
    id = 1;
end

switch id
    case 1  % CdSe / ZnS -- mechanistic baseline
        v = [1.840, 4.90e-4, 230, 0.13, 0.45, 9.5, 1.50, -2.30, ...
             0.90, 0.60, 0.28, 0.59, 5.00e7, 2.142857142857143e7, ...
             5.0e-22, 2.00e10, 1.48527e-18, 0.026, 5.6, 0.608, ...
             0.025, 0.92, 0.35, 1.0e7];
    case 2  % InP / ZnSe -- empirical InP absorption; mechanistic perturbations
        v = [1.424, 4.90e-4, 327, 0.077, 0.60, 12.4, 1.50, -5.00, ...
             0.70, 0.50, 0.16, 0.60, 3.00e7, 2.00e7, ...
             5.0e-22, 1.00e10, 1.00e-18, 0.043, 10.0, 0.587, ...
             0.040, 0.78, 0.30, 1.0e7];
    case 3  % PbS / CdS -- empirical PbS absorption; nonparabolic fit included
        v = [0.410, -4.0e-4, 150, 0.090, 0.090, 17.2, 1.50, -4.00, ...
             0.80, 0.80, 0.20, 0.20, 1.00e6, 1.00e6, ...
             1.0e-21, 5.00e9, 3.00e-18, 0.026, 18.0, 0.594, ...
             0.020, 0.78, 0.25, 8.0e6];
    case 4  % CsPbBr3 -- tabulated cube optics and empirical ambient rates
        v = [2.400, -3.0e-4, 200, 0.150, 0.140, 7.3, 1.50, -2.00, ...
             1.20, 1.20, 0.30, 0.30, 1.00e8, 2.00e7, ...
             5.0e-22, 2.00e10, 2.00e-18, 0.018, 7.0, 0.587, ...
             0.040, 0.80, 0.20, 1.0e7];
    case 5  % CdSe core -- empirical optical accuracy preset, D=3-8 nm at 300 K
        v = [1.840, 4.90e-4, 230, 0.12226086, 0.13097015, 11.385026, 1.50, -2.30, ...
             0.16200110, 0.66698257, 0.28, 0.59, 4.08904e7, 2.142857142857143e7, ...
             5.0e-22, 2.00e10, 1.48527e-18, 0.026, 5.6, 0.608, ...
             0.025, 0.90, 0.35, 1.0e7];
    otherwise
        v = [1.840, 4.90e-4, 230, 0.13, 0.45, 9.5, 1.50, -2.30, ...
             0.90, 0.60, 0.28, 0.59, 5.00e7, 2.142857142857143e7, ...
             5.0e-22, 2.00e10, 1.48527e-18, 0.026, 5.6, 0.608, ...
             0.025, 0.92, 0.35, 1.0e7];
end
end
