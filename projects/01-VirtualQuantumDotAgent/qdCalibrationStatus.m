function calibration = qdCalibrationStatus(effectiveInputs,result)
%QDCALIBRATIONSTATUS Observable-specific calibration scope and error levels.
%   This metadata distinguishes source-equation regression, internal frozen
%   evaluation, and external cross-source/protocol comparison.

id = round(effectiveInputs.materialID);
material = qdMaterialDatabase(id);
diameter_nm = 2*effectiveInputs.radius_nm;
cubeFactor = (3/(4*pi))^(1/3);
zeroFieldStrain = abs(effectiveInputs.electricField_kVcm) <= 1e-12 && ...
    abs(effectiveInputs.hydrostaticStrain_pct) <= 1e-12;
referenceBoundary = abs(effectiveInputs.environmentDielectric-2.25) <= 1e-9 && ...
    abs(effectiveInputs.electronBarrier_eV-material.electronBarrier_eV) <= 1e-9 && ...
    abs(effectiveInputs.holeBarrier_eV-material.holeBarrier_eV) <= 1e-9;
ambient = effectiveInputs.temperature_K >= 293 && ...
    effectiveInputs.temperature_K <= 303;
hasOverride = effectiveInputs.stokesShiftOverride_eV > 0;

calibration = struct();
calibration.active = id >= 2;
calibration.materialID = id;
calibration.modelTier = result.modelTier;
calibration.referenceObservable = 'none';
calibration.sizeDefinition = 'engine spherical core radius';
calibration.sourceSize_nm = diameter_nm;
calibration.opticalInScope = false;
calibration.plInScope = false;
calibration.kineticsInScope = false;
calibration.externalCrossSourceOpticalValidation = false;
calibration.externalKineticsValidation = false;
calibration.kineticsHoldoutValidation = false;
calibration.kineticsConditionalOnMeasuredPLEnergy = false;
calibration.endToEndSizeToKineticsValidated = false;
calibration.kineticTrainingRows = 0;
calibration.kineticTrainingEnergyGroups = 0;
calibration.kineticEvaluationRows = 0;
calibration.kineticEvaluationEnergyGroups = 0;
calibration.nearestKineticTrainingEnergyDistance_eV = NaN;
calibration.augerInScope = false;
calibration.augerSeriesValidation = false;
calibration.augerTrainingRows = 0;
calibration.augerReportedSeries = 0;
calibration.predictionClass = 'mechanistic prediction without material-specific calibration';
calibration.plBasis = 'material preset Stokes shift';
calibration.sources = cell(0,1);
calibration.errorMetrics = localEmptyMetrics();

if id == 2
    volume_nm3 = (4/3)*pi*effectiveInputs.radius_nm^3;
    tetrahedralEdge_nm = (6*sqrt(2)*volume_nm3)^(1/3);
    sizeOK = volume_nm3 >= 1.0-1e-9 && volume_nm3 <= 10.0+1e-9;
    bareCore = effectiveInputs.shellThickness_nm <= 0.05;
    calibration.referenceObservable = 'first absorption transition';
    calibration.sizeDefinition = ['regular-tetrahedron core edge; engine ' ...
        'radius is the equal-volume-sphere radius'];
    calibration.sourceSize_nm = tetrahedralEdge_nm;
    calibration.opticalInScope = sizeOK && ambient && bareCore && ...
        zeroFieldStrain && referenceBoundary;
    calibration.plInScope = calibration.opticalInScope && hasOverride;
    calibration.predictionClass = ...
        '2023 volume-based InP absorption equation plus mechanistic perturbation deltas';
    if hasOverride
        calibration.plBasis = 'user-supplied Stokes shift';
    else
        calibration.plBasis = 'uncalibrated room-temperature preset Stokes shift';
    end
    calibration.sources = { ...
        'Almeida et al., Nano Letters (2023), DOI 10.1021/acs.nanolett.3c02630'};
    calibration.errorMetrics.referenceEquationRegressionTolerance_eV = 2e-12;
    calibration.errorMetrics.outOfScopeCoreShellAbsorptionSingleError_eV = ...
        -0.206795078157;
    calibration.errorMetrics.outOfScopeCoreShellPLSingleError_eV = ...
        -0.096795078157;

elseif id == 3
    sizeOK = diameter_nm >= 3.9-1e-9 && diameter_nm <= 13.3+1e-9;
    bareCore = effectiveInputs.shellThickness_nm <= 0.05;
    supportedCoreShell = diameter_nm >= 3.9 && diameter_nm <= 5.8 && ...
        effectiveInputs.shellThickness_nm >= 0.5 && ...
        effectiveInputs.shellThickness_nm <= 1.25;
    calibration.referenceObservable = ...
        'first-exciton absorption transition and biexciton Auger lifetime';
    calibration.sizeDefinition = 'PbS core diameter (shell excluded)';
    calibration.opticalInScope = sizeOK && ambient && ...
        (bareCore || supportedCoreShell) && zeroFieldStrain && referenceBoundary;
    calibration.plInScope = calibration.opticalInScope && hasOverride;
    [~,~,augerGeometryInScope] = qdPbSCdSAugerModel( ...
        diameter_nm,effectiveInputs.shellThickness_nm);
    calibration.augerInScope = augerGeometryInScope && ambient && ...
        zeroFieldStrain;
    calibration.augerSeriesValidation = true;
    calibration.augerTrainingRows = 13;
    calibration.augerReportedSeries = 3;
    calibration.predictionClass = ...
        ['published PbS absorption law plus mechanistic deltas and a ' ...
        'domain-gated PbS/CdS Auger learner'];
    if hasOverride
        calibration.plBasis = 'user-supplied Stokes shift';
    else
        calibration.plBasis = 'uncalibrated preset Stokes shift';
    end
    calibration.sources = { ...
        'Moreels et al., ACS Nano 3 (2009), DOI 10.1021/nn900863a'; ...
        'Justo et al., J. Phys. Chem. C 117 (2013), DOI 10.1021/jp406774p'; ...
        ['Stylianou et al., Nano Letters (2026), DOI ' ...
        '10.1021/acs.nanolett.6c00158']};
    calibration.errorMetrics.referenceEquationRegressionTolerance_eV = 2e-12;
    calibration.errorMetrics.thickShellPLHoldoutRMSE_eV = 0.134996078;
    calibration.errorMetrics.thickShellOverlapHoldoutRMSE = 0.174547032821;
    calibration.errorMetrics.augerLifetimeSeriesCVRMSE_ps = ...
        8.94628287305148;
    calibration.errorMetrics.augerLifetimeSeriesCVMAE_ps = ...
        6.51825648973855;
    calibration.errorMetrics.augerLifetimeSeriesCVQSquared = ...
        0.971439864538964;
    calibration.errorMetrics.genericAugerBaselineRMSE_ps = ...
        100.687978271488;

elseif id == 4
    edge_nm = effectiveInputs.radius_nm/cubeFactor;
    sizeOK = edge_nm >= 3.0-1e-9 && edge_nm <= 12.8+1e-9;
    bareCore = effectiveInputs.shellThickness_nm <= 0.05;
    opticalTemperatureOK = effectiveInputs.temperature_K >= 250 && ...
        effectiveInputs.temperature_K <= 300;
    energyOK = result.plEnergy_eV >= 2.445466802 && ...
        result.plEnergy_eV <= 2.654928626;
    calibration.referenceObservable = ...
        'absorption, PL peak, Stokes shift, PLQY, and time-resolved PL rates';
    calibration.sizeDefinition = ...
        'nanocube edge length (engine radius is equal-volume-sphere radius)';
    calibration.sourceSize_nm = edge_nm;
    calibration.opticalInScope = sizeOK && opticalTemperatureOK && bareCore && ...
        zeroFieldStrain && referenceBoundary;
    calibration.plInScope = calibration.opticalInScope;
    calibration.kineticsInScope = calibration.opticalInScope && ambient && ...
        energyOK && effectiveInputs.surfaceTrapDensity_cm2 == 0;
    calibration.externalCrossSourceOpticalValidation = true;
    calibration.externalKineticsValidation = false;
    calibration.kineticsHoldoutValidation = true;
    calibration.kineticsConditionalOnMeasuredPLEnergy = true;
    calibration.endToEndSizeToKineticsValidated = false;
    calibration.kineticTrainingRows = 25;
    calibration.kineticTrainingEnergyGroups = 16;
    calibration.kineticEvaluationRows = 9;
    calibration.kineticEvaluationEnergyGroups = 5;
    kineticTrainingEnergy_eV = [2.445466802;2.450299740;2.460023152; ...
        2.464913854;2.469824041;2.479703337;2.484672682;2.499700945; ...
        2.530309528;2.535483985;2.551135120;2.577654197;2.588416845; ...
        2.593831943;2.643606969;2.654928626];
    calibration.nearestKineticTrainingEnergyDistance_eV = min(abs( ...
        result.plEnergy_eV-kineticTrainingEnergy_eV));
    calibration.predictionClass = ...
        ['2017 nanocube table plus external cross-source comparison and a ' ...
        'physics-constrained ridge kinetic learner'];
    if hasOverride
        calibration.plBasis = 'user-supplied Stokes shift';
    else
        calibration.plBasis = 'source-tabulated PL and Stokes relation';
    end
    calibration.sources = { ...
        'Brennan et al., JACS (2017), DOI 10.1021/jacs.7b05683'; ...
        'Mondal et al., Chemical Science (2019), DOI 10.1039/C9SC01339C'; ...
        'Abbas et al., Nature Communications 16 (2025), DOI 10.1038/s41467-025-60848-5'};
    calibration.errorMetrics.externalCrossSourceAbsorptionRMSE_eV = ...
        0.0695873611114;
    calibration.errorMetrics.externalCrossSourceAbsorptionBias_eV = ...
        0.0649090909091;
    calibration.errorMetrics.crossProtocolPLAnchorRMSE_eV = ...
        0.0436756975817;
    calibration.errorMetrics.radiativeRateCalibrationRMSE_nsInv = ...
        0.0104344089289773;
    calibration.errorMetrics.radiativeRateHoldoutRMSE_nsInv = ...
        0.0145593421577936;
    calibration.errorMetrics.nonradiativeRateCalibrationRMSE_nsInv = ...
        0.00898327318561782;
    calibration.errorMetrics.nonradiativeRateHoldoutRMSE_nsInv = ...
        0.0103094382867921;
    calibration.errorMetrics.totalLifetimeHoldoutRMSE_ns = ...
        0.0896422531098704;
    calibration.errorMetrics.radiativeLifetimeHoldoutRMSE_ns = ...
        0.180420528355052;
    calibration.errorMetrics.plqyHoldoutRMSE_percentagePoints = ...
        3.48660783201446;
    calibration.errorMetrics.kineticDevelopmentCVCompositeRatio = ...
        0.799362905374656;

elseif id == 5
    calibration.referenceObservable = 'first-exciton absorption transition';
    calibration.sizeDefinition = 'CdSe core diameter';
    calibration.opticalInScope = diameter_nm >= 3 && diameter_nm <= 8 && ...
        effectiveInputs.temperature_K >= 250 && ...
        effectiveInputs.temperature_K <= 350 && zeroFieldStrain && ...
        effectiveInputs.shellThickness_nm <= 0.05 && ...
        abs(effectiveInputs.environmentDielectric-2.25) <= 0.50;
    calibration.plInScope = calibration.opticalInScope && hasOverride;
    calibration.predictionClass = ...
        'effective fit to the mean of three published CdSe sizing equations';
    calibration.sources = { ...
        'Yu et al. (2003), DOI 10.1021/cm034081k'; ...
        'Jasieniak et al. (2009), DOI 10.1021/jp906827m'; ...
        'de Mello Donega and Koole (2009), DOI 10.1021/jp811329r'};
    calibration.errorMetrics.calibrationRMSE_eV = 0.000371;
end

if calibration.opticalInScope
    calibration.opticalStatus = 'inside published calibration envelope';
else
    calibration.opticalStatus = 'outside published calibration envelope';
end
if calibration.plInScope
    calibration.plStatus = 'source-supported or user-supplied Stokes/PL relation';
else
    calibration.plStatus = 'PL wavelength is not independently calibrated';
end
if calibration.kineticsInScope
    calibration.kineticsStatus = ['inside grouped-evaluation kinetic envelope; ' ...
        'accuracy is conditional on PL energy'];
else
    calibration.kineticsStatus = 'kinetic rates are generic or outside calibration scope';
end
end

function metrics = localEmptyMetrics()
metrics = struct( ...
    'referenceEquationRegressionTolerance_eV',NaN, ...
    'calibrationRMSE_eV',NaN, ...
    'sizeBridgeSingleHoldoutAbsoluteError_eV',NaN, ...
    'externalCrossSourceAbsorptionRMSE_eV',NaN, ...
    'externalCrossSourceAbsorptionBias_eV',NaN, ...
    'crossProtocolPLAnchorRMSE_eV',NaN, ...
    'outOfScopeCoreShellAbsorptionSingleError_eV',NaN, ...
    'outOfScopeCoreShellPLSingleError_eV',NaN, ...
    'thickShellPLHoldoutRMSE_eV',NaN, ...
    'thickShellOverlapHoldoutRMSE',NaN, ...
    'augerLifetimeSeriesCVRMSE_ps',NaN, ...
    'augerLifetimeSeriesCVMAE_ps',NaN, ...
    'augerLifetimeSeriesCVQSquared',NaN, ...
    'genericAugerBaselineRMSE_ps',NaN, ...
    'stokesCalibrationRMSE_eV',NaN, ...
    'stokesHoldoutRMSE_eV',NaN, ...
    'radiativeRateCalibrationRMSE_nsInv',NaN, ...
    'radiativeRateHoldoutRMSE_nsInv',NaN, ...
    'nonradiativeRateCalibrationRMSE_nsInv',NaN, ...
    'nonradiativeRateHoldoutRMSE_nsInv',NaN, ...
    'totalLifetimeHoldoutRMSE_ns',NaN, ...
    'radiativeLifetimeHoldoutRMSE_ns',NaN, ...
    'plqyHoldoutRMSE_percentagePoints',NaN, ...
    'kineticDevelopmentCVCompositeRatio',NaN);
end
