function messages = qdDecodeFlags(flags)
%QDDECODEFLAGS Convert the validity bitmask to readable diagnostics.

definitions = { ...
    1, 'Radius was invalid or clipped to the supported numeric range.'; ...
    2, 'Temperature was invalid or clipped.'; ...
    4, 'Electric field exceeds the weak-field perturbative envelope.'; ...
    8, 'Hydrostatic strain exceeds the calibrated +/-3 percent envelope.'; ...
    16, 'No bound electron ground state was found for the supplied barrier.'; ...
    32, 'No bound hole ground state was found for the supplied barrier.'; ...
    64, 'Radius approaches the atomistic regime; EMA confidence is reduced.'; ...
    128, 'Radius is outside the strong-confinement envelope.'; ...
    256, 'Material ID was invalid, noninteger, or replaced by material 1.'; ...
    512, 'Pump lies below the first absorption transition (tail model used).'; ...
    1024, 'Population state required normalization or reset.'; ...
    2048, 'A barrier override was clipped.'; ...
    4096, 'The inverse-design radius sensitivity was too small.'; ...
    8192, 'Pump input was invalid and replaced.'; ...
    16384, 'Shell thickness was invalid and replaced.'; ...
    32768, 'Trap density was invalid and replaced.'; ...
    65536, 'Environment permittivity was invalid and replaced.'; ...
    131072, 'Optical generation rate reached the protective model cap.'; ...
    262144, 'A populated kinetic channel is faster than the 10 ps output sampling.'; ...
    524288, 'Empirical CdSe preset is outside its 3-8 nm, near-300 K calibration envelope.'; ...
    1048576, 'Stokes-shift override was invalid or clipped.'; ...
    2097152, 'Empirical optical baseline is outside its published size/temperature/perturbation envelope.'; ...
    4194304, 'PL/Stokes wavelength is not calibrated for this material and scenario.'; ...
    8388608, 'Core/shell geometry is outside the source-supported transfer range.'; ...
    16777216, ['One or more kinetic rates are generic or outside their ' ...
        'grouped-validation envelope.']};

mask = uint32(round(flags));
messages = cell(size(definitions,1),1);
numberOfMessages = 0;
for k = 1:size(definitions,1)
    if bitand(mask,uint32(definitions{k,1})) ~= 0
        numberOfMessages = numberOfMessages+1;
        messages{numberOfMessages,1} = definitions{k,2};
    end
end
if numberOfMessages == 0
    messages = {'Inputs are inside the model validity checks.'};
else
    messages = messages(1:numberOfMessages);
end
end
