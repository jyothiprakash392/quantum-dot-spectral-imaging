function prediction = predictQDWithError(qdInput,numberOfSamples)
%PREDICTQDWITHERROR Prediction plus input and benchmark error estimates.
%   P = PREDICTQDWITHERROR(INPUTS,400) accepts a qdDefaultInputs structure.
%   A scalar first argument is interpreted as CdSe core radius in nm.
%
%   The scenario interval propagates explicit engineering assumptions.
%   Observable-specific benchmark data are reported only inside each
%   material's calibration envelope. Held-out RMSE and calibration-curve
%   residuals are kept separate; neither is a formal confidence interval.

defaults = qdDefaultInputs();
if nargin < 1 || isempty(qdInput)
    qdInput = defaults;
elseif isnumeric(qdInput) && isscalar(qdInput)
    defaults.radius_nm = qdInput;
    qdInput = defaults;
elseif isstruct(qdInput)
    names = fieldnames(defaults);
    for k = 1:numel(names)
        if ~isfield(qdInput,names{k})
            qdInput.(names{k}) = defaults.(names{k});
        end
    end
else
    error('VirtualQD:PredictionInput', ...
        'First input must be a qdInput structure or scalar radius in nm.');
end
if nargin < 2
    numberOfSamples = 400;
end
validateattributes(numberOfSamples,{'numeric'},{'scalar','integer','>=',100});

nominal = simulateQD(qdInput,'Duration_ns',0);
nominalEnergy = nominal.absorptionEnergy_eV;
hc_eVnm = 1239.841984332;

% Seeded local sensitivity interval using the same declared assumptions as
% validateAgainstRealCdSe. Barrier value 0 means use the material preset.
material = qdMaterialDatabase(qdInput.materialID);
if qdInput.electronBarrier_eV > 0
    centerElectronBarrier = qdInput.electronBarrier_eV;
else
    centerElectronBarrier = material.electronBarrier_eV;
end
if qdInput.holeBarrier_eV > 0
    centerHoleBarrier = qdInput.holeBarrier_eV;
else
    centerHoleBarrier = material.holeBarrier_eV;
end

rng(42,'twister');
scenarioEnergy = zeros(numberOfSamples,1);
for sample = 1:numberOfSamples
    sampled = qdInput;
    sampled.radius_nm = max(0.5,qdInput.radius_nm*(1+0.03*randn));
    sampled.temperature_K = min(1000,max(0,qdInput.temperature_K+5*randn));
    sampled.electronBarrier_eV = min(20,max(0.05,centerElectronBarrier+0.12*randn));
    sampled.holeBarrier_eV = min(20,max(0.05,centerHoleBarrier+0.10*randn));
    sampled.environmentDielectric = min(20,max(1, ...
        qdInput.environmentDielectric+0.25*randn));
    [y,~] = qdPhysicsStep(qdPackInputs(sampled),[1;0;0;0],0);
    scenarioEnergy(sample) = y(8);
end
ordered = sort(scenarioEnergy);
scenarioLow = localOrderStatistic(ordered,0.025);
scenarioMedian = localOrderStatistic(ordered,0.50);
scenarioHigh = localOrderStatistic(ordered,0.975);

prediction = struct();
prediction.inputs = qdInput;
prediction.nominal = nominal;
prediction.absorptionEnergy_eV = nominalEnergy;
prediction.absorptionWavelength_nm = hc_eVnm/nominalEnergy;
prediction.scenarioMedian_eV = scenarioMedian;
prediction.scenarioLow95_eV = scenarioLow;
prediction.scenarioHigh95_eV = scenarioHigh;
prediction.scenarioAssumptions = struct( ...
    'radiusRelativeSigma',0.03,'temperatureSigma_K',5, ...
    'electronBarrierSigma_eV',0.12,'holeBarrierSigma_eV',0.10, ...
    'environmentDielectricSigma',0.25,'numberOfSamples',numberOfSamples, ...
    'seed',42,'interpretation','input-sensitivity scenario, not calibrated CI');

diameter_nm = 2*qdInput.radius_nm;
effectiveProfile = nominal.effectiveInputs;
materialID = round(qdInput.materialID);
isCdSeProfile = materialID == 1 || materialID == 5;
isBenchmarkable = isCdSeProfile && ...
    diameter_nm >= 3 && diameter_nm <= 8 && ...
    abs(effectiveProfile.temperature_K-300) <= 1.0e-9 && ...
    abs(effectiveProfile.electricField_kVcm) <= 1.0e-12 && ...
    abs(effectiveProfile.hydrostaticStrain_pct) <= 1.0e-12 && ...
    effectiveProfile.shellThickness_nm <= 1.0e-12 && ...
    abs(effectiveProfile.environmentDielectric-2.25) <= 1.0e-9 && ...
    abs(effectiveProfile.electronBarrier_eV-material.electronBarrier_eV) <= 1.0e-9 && ...
    abs(effectiveProfile.holeBarrier_eV-material.holeBarrier_eV) <= 1.0e-9;
isMultiMaterialBenchmarkable = materialID >= 2 && materialID <= 4 && ...
    nominal.calibration.opticalInScope;

if isMultiMaterialBenchmarkable
    [referenceAbsorption_eV,referencePL_eV,~,sourceSize_nm] = ...
        qdEmpiricalMaterialReference(materialID,qdInput.radius_nm, ...
        effectiveProfile.temperature_K);
    benchmarkResidual = nominalEnergy-referenceAbsorption_eV;
    calibrationMetrics = nominal.calibration.errorMetrics;
    if materialID == 2
        source = 'Almeida et al., Nano Letters 2023';
        doi = 'https://doi.org/10.1021/acs.nanolett.3c02630';
        scope = ['InP core volume 1-10 nm^3, approximately tetrahedral, ' ...
            '293-303 K, bare core, zero field/strain'];
        metricInterpretation = ['Exact regression to the published volume ' ...
            'equation. No independent held-out energy RMSE is claimed.'];
        energyRMSE = NaN;
        externalCrossSource = false;
    elseif materialID == 3
        source = 'Moreels et al., ACS Nano 2009; Justo et al., JPC C 2013';
        doi = 'https://doi.org/10.1021/nn900863a';
        scope = ['PbS core diameter 3.9-13.3 nm at 293-303 K; bare core ' ...
            'or source-supported cation-exchanged CdS shell'];
        metricInterpretation = ['Exact regression to the published first-' ...
            'exciton sizing equation. The source reports about 10 percent ' ...
            'diameter distributions; no independent energy RMSE is claimed.'];
        energyRMSE = NaN;
        externalCrossSource = false;
    else
        source = ['Brennan et al., JACS 2017; Mondal et al., Chemical ' ...
            'Science 2019; Abbas et al., Nature Communications 2025'];
        doi = 'https://doi.org/10.1021/jacs.7b05683';
        scope = ['CsPbBr3 cube edge 3-12.8 nm, bare cube, zero field/strain; ' ...
            'temperature correction restricted to 250-300 K'];
        metricInterpretation = ['signedError_eV is the residual against the ' ...
            'Brennan calibration table, normally zero at source nodes. ' ...
            'energyRMSE_eV is a separate external cross-source/protocol ' ...
            'comparison over 3.0-6.2 nm; it is not a per-case residual.'];
        energyRMSE = calibrationMetrics.externalCrossSourceAbsorptionRMSE_eV;
        externalCrossSource = true;
    end
    if isnan(energyRMSE)
        prediction.engineeringEnvelopeLow_eV = scenarioLow;
        prediction.engineeringEnvelopeHigh_eV = scenarioHigh;
    else
        prediction.engineeringEnvelopeLow_eV = min(scenarioLow, ...
            nominalEnergy-energyRMSE);
        prediction.engineeringEnvelopeHigh_eV = max(scenarioHigh, ...
            nominalEnergy+energyRMSE);
    end
    prediction.approximateCombinedLow95_eV = prediction.engineeringEnvelopeLow_eV;
    prediction.approximateCombinedHigh95_eV = prediction.engineeringEnvelopeHigh_eV;
    prediction.benchmark = struct( ...
        'available',true,'source',source,'doi',doi, ...
        'observable','first optical transition energy', ...
        'sourceSize_nm',sourceSize_nm, ...
        'referenceAbsorptionEnergy_eV',referenceAbsorption_eV, ...
        'referencePLEnergy_eV',referencePL_eV, ...
        'signedError_eV',benchmarkResidual, ...
        'calibrationReferenceResidual_eV',benchmarkResidual, ...
        'energyRMSE_eV',energyRMSE, ...
        'externalCrossSourceValidation',externalCrossSource, ...
        'metricInterpretation',metricInterpretation,'scope',scope, ...
        'calibrationStatus',nominal.calibration);
    if materialID == 4
        prediction.benchmark.externalCrossSourceBias_eV = ...
            calibrationMetrics.externalCrossSourceAbsorptionBias_eV;
        prediction.benchmark.crossProtocolPLAnchorRMSE_eV = ...
            calibrationMetrics.crossProtocolPLAnchorRMSE_eV;
        prediction.radiativeLifetimeBenchmark = struct( ...
            'available',nominal.calibration.kineticsInScope, ...
            'conditionalOnPLEnergy',true, ...
            'endToEndSizeToKineticsValidated',false, ...
            'modelIntrinsicRadiativeLifetime_ns',1e9/nominal.radiativeRate_Hz, ...
            'heldOutRadiativeLifetimeRMSE_ns', ...
                calibrationMetrics.radiativeLifetimeHoldoutRMSE_ns, ...
            'heldOutTotalLifetimeRMSE_ns', ...
                calibrationMetrics.totalLifetimeHoldoutRMSE_ns, ...
            'heldOutPLQYRMSE_percentagePoints', ...
                calibrationMetrics.plqyHoldoutRMSE_percentagePoints, ...
            'source','Abbas et al., Nature Communications 2025', ...
            'doi','https://doi.org/10.1038/s41467-025-60848-5', ...
            'interpretation',['Grouped errors are conditional on PL energy; ' ...
                'predicted size-to-PL uncertainty is not included.']);
        prediction.benchmark.externalPerCaseResidualAvailable = false;
        prediction.agreementGrade = [ ...
            'calibration reference reproduced; external cross-source RMSE ' ...
            'is a model-form scale, not a per-case score'];
    else
        prediction.radiativeLifetimeBenchmark = struct('available',false, ...
            'reason','No universal held-out kinetic calibration is available.');
        prediction.agreementGrade = ...
            'published reference equation reproduced; independent RMSE unavailable';
    end
    if materialID == 3
        prediction.augerLifetimeBenchmark = struct( ...
            'available',nominal.calibration.augerInScope, ...
            'biexcitonAugerLifetime_ps',1e12/nominal.augerRate_Hz, ...
            'wholeSeriesCVRMSE_ps', ...
                calibrationMetrics.augerLifetimeSeriesCVRMSE_ps, ...
            'wholeSeriesCVMAE_ps', ...
                calibrationMetrics.augerLifetimeSeriesCVMAE_ps, ...
            'wholeSeriesCVQSquared', ...
                calibrationMetrics.augerLifetimeSeriesCVQSquared, ...
            'trainingRows',nominal.calibration.augerTrainingRows, ...
            'reportedSeries',nominal.calibration.augerReportedSeries, ...
            'source','Stylianou et al., Nano Letters 2026', ...
            'doi','https://doi.org/10.1021/acs.nanolett.6c00158', ...
            'interpretation',['Provisional low-occupancy biexciton Auger ' ...
                'calibration; other ID-3 kinetic channels remain generic.']);
    else
        prediction.augerLifetimeBenchmark = struct('available',false, ...
            'reason','No separately validated Auger-lifetime learner is active.');
    end
    prediction.approximateCombinedIntervalInterpretation = [ ...
        'Input-sensitivity scenario combined with an external model-form RMSE ' ...
        'only when one exists. It is an engineering envelope, not a 95% CI.'];
elseif isBenchmarkable
    empirical = qdCdSeEmpiricalReferences(diameter_nm);
    benchmarkWavelength = empirical.YuWavelength_nm;
    benchmarkEnergy = empirical.YuEnergy_eV;
    benchmarkResidual = nominalEnergy-benchmarkEnergy;
    if materialID == 5
        accuracy = localCalibratedAccuracy();
        energyRMSE = accuracy.vsMeanRMSE_eV;
        wavelengthRMSE = accuracy.vsMeanWavelengthRMSE_nm;
        scope = ['Effective CdSe-core optical calibration, diameter 3-8 nm, ' ...
            '300 K, zero field/strain, no shell, epsilon_out = 2.25'];
        metricInterpretation = ['Calibration residual against the mean of ' ...
            'three published sizing equations; it is not held-out accuracy.'];
    else
        rootFolder = fileparts(mfilename('fullpath'));
        validationData = load(fullfile(rootFolder,'RealWorldValidation.mat'),'report');
        if diameter_nm >= 4
            energyRMSE = validationData.report.finiteBarrier.diameterAtLeast4nm.energy.RMSE;
            wavelengthRMSE = validationData.report.finiteBarrier.diameterAtLeast4nm.wavelength.RMSE;
            scope = ['Mechanistic CdSe benchmark profile, diameter 4-8 nm, ' ...
                '300 K, zero field/strain, no shell, epsilon_out = 2.25'];
        else
            energyRMSE = validationData.report.finiteBarrier.energy.RMSE;
            wavelengthRMSE = validationData.report.finiteBarrier.wavelength.RMSE;
            scope = ['Mechanistic CdSe benchmark profile, diameter 3-8 nm, ' ...
                '300 K, zero field/strain, no shell; small-dot caution'];
        end
        metricInterpretation = ['Agreement with published sizing equations ' ...
            'on the stated evaluation grid; not a confidence interval.'];
    end
    % A deterministic engineering envelope keeps three distinct effects
    % visible: the sampled input scenario, source-to-source disagreement,
    % and the measured diameter uncertainty reported by Donega/Koole.
    sizeHalfWidth = empirical.DonegaDiameterUncertaintyHalfWidth_eV;
    prediction.engineeringEnvelopeLow_eV = min([scenarioLow, ...
        empirical.ReferenceMinEnergy_eV-sizeHalfWidth,nominalEnergy-energyRMSE]);
    prediction.engineeringEnvelopeHigh_eV = max([scenarioHigh, ...
        empirical.ReferenceMaxEnergy_eV+sizeHalfWidth,nominalEnergy+energyRMSE]);
    % Backward-compatible field aliases. Despite their historical names,
    % these are not statistical 95 percent confidence bounds.
    prediction.approximateCombinedLow95_eV = prediction.engineeringEnvelopeLow_eV;
    prediction.approximateCombinedHigh95_eV = prediction.engineeringEnvelopeHigh_eV;
    prediction.benchmark = struct( ...
        'available',true,'source',['Yu 2003; Jasieniak 2009; ' ...
            'de Mello Donega/Koole 2009'], ...
        'doi','https://doi.org/10.1021/cm034081k', ...
        'firstExcitonEnergy_eV',benchmarkEnergy, ...
        'firstExcitonWavelength_nm',benchmarkWavelength, ...
        'signedError_eV',benchmarkResidual, ...
        'signedError_nm',prediction.absorptionWavelength_nm-benchmarkWavelength, ...
        'energyRMSE_eV',energyRMSE,'wavelengthRMSE_nm',wavelengthRMSE, ...
        'metricInterpretation',metricInterpretation, ...
        'scope',scope, ...
        'jasieniakEnergy_eV',empirical.JasieniakEnergy_eV, ...
        'signedErrorVsJasieniak_eV', ...
            nominalEnergy-empirical.JasieniakEnergy_eV, ...
        'donegaEnergy_eV',empirical.DonegaEnergy_eV, ...
        'signedErrorVsDonega_eV',nominalEnergy-empirical.DonegaEnergy_eV, ...
        'threeCurveMeanEnergy_eV',empirical.ReferenceMeanEnergy_eV, ...
        'signedErrorVsThreeCurveMean_eV', ...
            nominalEnergy-empirical.ReferenceMeanEnergy_eV, ...
        'interCurveSpread_eV',empirical.InterCurveSpread_eV, ...
        'donegaDiameterUncertaintyHalfWidth_eV', ...
            empirical.DonegaDiameterUncertaintyHalfWidth_eV, ...
        'interpretation',['Empirical-curve spread is a systematic reference ' ...
            'choice diagnostic, not a statistical confidence interval.']);
    referenceRadiativeRate_per_ns = -0.1151+0.0753*nominal.plEnergy_eV;
    prediction.radiativeLifetimeBenchmark = struct( ...
        'available',referenceRadiativeRate_per_ns > 0, ...
        'modelIntrinsicRadiativeLifetime_ns',1e9/nominal.radiativeRate_Hz, ...
        'referenceRadiativeLifetime_ns',1/referenceRadiativeRate_per_ns, ...
        'relativeError_percent',100*((1e9/nominal.radiativeRate_Hz)- ...
            1/referenceRadiativeRate_per_ns)/(1/referenceRadiativeRate_per_ns), ...
        'source','de Mello Donega and Koole, J. Phys. Chem. C 2009', ...
        'doi','https://doi.org/10.1021/jp811329r', ...
        'interpretation',['Intrinsic 1/radiativeRate comparison at the model ' ...
            'PL energy; do not substitute effectiveLifetime_ns.']);
    prediction.approximateCombinedIntervalInterpretation = [ ...
        'Engineering envelope spanning input sensitivity, the published ' ...
        'source range, reported diameter uncertainty, and one evaluation ' ...
        'RMSE. It is not a calibrated confidence interval.'];
    meanResidual = nominalEnergy-empirical.ReferenceMeanEnergy_eV;
    if abs(meanResidual) <= 0.015
        prediction.agreementGrade = 'good (<=15 meV versus source mean)';
    elseif abs(meanResidual) <= 0.050
        prediction.agreementGrade = 'moderate (>15-50 meV at this size)';
    else
        prediction.agreementGrade = 'poor (>50 meV; model refinement required)';
    end
else
    prediction.engineeringEnvelopeLow_eV = NaN;
    prediction.engineeringEnvelopeHigh_eV = NaN;
    prediction.approximateCombinedLow95_eV = NaN;
    prediction.approximateCombinedHigh95_eV = NaN;
    prediction.benchmark = struct('available',false, ...
        'reason',['Benchmark metrics require an observable-specific calibrated ' ...
        'material profile inside its published size, temperature, geometry, ' ...
        'field, strain, dielectric, and barrier envelope. Other cases are ' ...
        'predictions, not experimentally scored validations.']);
    prediction.agreementGrade = 'unvalidated scenario';
    prediction.radiativeLifetimeBenchmark = struct('available',false, ...
        'reason',['No kinetic benchmark is available for this material and ' ...
        'scenario inside its observable-specific source envelope.']);
    prediction.approximateCombinedIntervalInterpretation = ...
        'Unavailable outside the applicable material/observable comparison scope.';
end
end

function accuracy = localCalibratedAccuracy()
% Recompute the small calibration summary if the generated artifact is not
% present. A persistent cache avoids repeating the dense size sweep.
persistent cachedAccuracy
if ~isempty(cachedAccuracy)
    accuracy = cachedAccuracy;
    return
end
diameter_nm = (3:0.25:8).';
reference = qdCdSeEmpiricalReferences(diameter_nm);
predicted_eV = zeros(size(diameter_nm));
for k = 1:numel(diameter_nm)
    inputs = qdAccurateCdSeInputs(diameter_nm(k)/2);
    result = simulateQD(inputs,'Duration_ns',0);
    predicted_eV(k) = result.absorptionEnergy_eV;
end
residual_eV = predicted_eV-reference.ReferenceMeanEnergy_eV;
predictedWavelength_nm = 1239.841984332./predicted_eV;
referenceWavelength_nm = 1239.841984332./reference.ReferenceMeanEnergy_eV;
cachedAccuracy = struct( ...
    'vsMeanRMSE_eV',sqrt(mean(residual_eV.^2)), ...
    'vsMeanWavelengthRMSE_nm',sqrt(mean( ...
        (predictedWavelength_nm-referenceWavelength_nm).^2)));
accuracy = cachedAccuracy;
end

function value = localOrderStatistic(ordered,p)
index = 1+(numel(ordered)-1)*p;
low = floor(index);
high = ceil(index);
if low == high
    value = ordered(low);
else
    fraction = index-low;
    value = ordered(low)*(1-fraction)+ordered(high)*fraction;
end
end
