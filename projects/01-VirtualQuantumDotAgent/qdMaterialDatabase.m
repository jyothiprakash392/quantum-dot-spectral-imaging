function material = qdMaterialDatabase(materialID)
%QDMATERIALDATABASE Human-readable material preset metadata.

if nargin == 0
    materialID = 1;
end
if ~isnumeric(materialID) || ~isscalar(materialID) || ...
        ~isreal(materialID) || ~isfinite(materialID)
    id = 1;
else
    id = round(materialID);
    if abs(materialID-id) > 1e-12
        id = 1;
    end
end
if id < 1 || id > 5
    id = 1;
end
v = qdMaterialVector(id);
names = {'CdSe/ZnS mechanistic','InP/ZnSe','PbS/CdS','CsPbBr3', ...
    'CdSe core empirical'};
statuses = {'benchmark-tested baseline', ...
    'empirical InP absorption: V=1-10 nm^3 near 300 K', ...
    'empirical PbS absorption plus domain-gated PbS/CdS Auger learner', ...
    'empirical CsPbBr3 cube optics: edge 3-12.8 nm; ambient kinetics', ...
    'empirically fitted: diameter 3-8 nm near 300 K'};

material = struct( ...
    'id', id, ...
    'name', names{id}, ...
    'status', statuses{id}, ...
    'Eg0_eV', v(1), ...
    'varshniAlpha_eV_K', v(2), ...
    'varshniBeta_K', v(3), ...
    'electronMass_m0', v(4), ...
    'holeMass_m0', v(5), ...
    'relativePermittivity', v(6), ...
    'nominalOutsideIndex', v(7), ...
    'hydrostaticGapDeformation_eV', v(8), ...
    'electronBarrier_eV', v(9), ...
    'holeBarrier_eV', v(10), ...
    'barrierElectronMass_m0', v(11), ...
    'barrierHoleMass_m0', v(12), ...
    'radiativeRate_Hz', v(13), ...
    'nonradiativeRate_Hz', v(14), ...
    'trapCrossSection_m2', v(15), ...
    'augerRateAt3nm_Hz', v(16), ...
    'absorptionCrossSectionAt350nm3nm_m2', v(17), ...
    'LOPhononEnergy_eV', v(18), ...
    'excitonBohrRadius_nm', v(19), ...
    'latticeConstant_nm', v(20), ...
    'stokesShift_eV', v(21), ...
    'priorConfidence', v(22), ...
    'trapDepth_eV', v(23), ...
    'trapDecayRate_Hz', v(24));

material.geometry = 'spherical effective-mass core';
material.sizeDefinition = 'radius_nm is spherical core radius';
material.calibratedObservable = 'none';
material.calibrationScope = 'none';
material.primarySources = cell(0,1);

if id == 1
    material.note = ['CdSe/ZnS is the mechanistic default. Band offsets, trap ' ...
        'data, and kinetic rates remain sample-dependent parameters.'];
elseif id == 2
    material.geometry = 'approximately regular-tetrahedral InP core';
    material.sizeDefinition = ['radius_nm is equal-volume-sphere radius; ' ...
        'use qdCalibratedMaterialInputs with tetrahedral edge length'];
    material.calibratedObservable = 'first absorption transition';
    material.calibrationScope = ['InP volume 1-10 nm^3, 293-303 K, zero ' ...
        'field/strain, bare core, reference dielectric/barriers'];
    material.primarySources = { ...
        '10.1021/acs.nanolett.3c02630'; ...
        '10.1021/acsphotonics.8b00615'};
    material.note = ['The optical baseline is a published volume-based InP ' ...
        'core relation. ZnSe-shell PL, Stokes shift, QY, and lifetime remain ' ...
        'protocol-specific; shell thickness above the 0.05 nm numerical ' ...
        'bare-core tolerance is explicitly flagged.'];
elseif id == 3
    material.geometry = 'spherical PbS core with optional cation-exchanged CdS shell';
    material.sizeDefinition = 'radius_nm is PbS core radius, excluding CdS shell';
    material.calibratedObservable = ...
        'first-exciton absorption and domain-gated biexciton Auger lifetime';
    material.calibrationScope = ['PbS core diameter 3.9-13.3 nm, 293-303 K; ' ...
        'bare core or conservative cation-exchanged shell transfer'];
    material.primarySources = {'10.1021/nn900863a';'10.1021/jp406774p'; ...
        '10.1021/acs.nanolett.6c00158'};
    material.note = ['The PbS absorption sizing equation is empirical and ' ...
        'includes nonparabolic behavior. A separate 13-row, three-series ' ...
        '2026 learner calibrates Auger lifetime only inside its convex ' ...
        'cation-exchange geometry envelope. PL, QY, total lifetime, and ' ...
        'thick-shell quasi-type-II behavior remain sample-specific.'];
elseif id == 4
    material.geometry = 'CsPbBr3 nanocube';
    material.sizeDefinition = ['radius_nm is equal-volume-sphere radius; ' ...
        'use qdCalibratedMaterialInputs with cube edge length'];
    material.calibratedObservable = ...
        'absorption, PL, Stokes shift, ambient radiative/nonradiative rates';
    material.calibrationScope = ['cube edge 3-12.8 nm, optical temperature ' ...
        '250-300 K, bare cube; kinetic fit at 293-303 K and PL 2.445-2.655 eV'];
    material.primarySources = { ...
        '10.1021/jacs.7b05683'; ...
        '10.1021/acs.jpcc.4c06265'; ...
        '10.1038/s41467-025-60848-5'};
    material.note = ['Optical interpolation uses primary nanocube SI points. ' ...
        'Kinetic rates use a separate high-PLQY synthesis dataset; protocol ' ...
        'differences remain a real model-form uncertainty.'];
elseif id == 5
    material.note = ['Effective optical parameters fitted to the mean of Yu ' ...
        '(2003), Jasieniak (2009), and de Mello Donega/Koole (2009) CdSe ' ...
        'core sizing curves. Use near 300 K, zero field/strain, diameter ' ...
        '3-8 nm; do not interpret the fitted masses and permittivity as a ' ...
        'new bulk-material measurement.'];
end
end
