function paths = qdPackagePaths()
%QDPACKAGEPATHS Resolve canonical package and generated-artifact folders.

commonFolder = fileparts(mfilename('fullpath'));
sourceFolder = fileparts(commonFolder);
packageRoot = fileparts(sourceFolder);
runtimeRoot = fullfile(tempdir,'QDVoltageSelectedDualConverter', ...
    ['MATLAB-' version('-release')]);

paths = struct( ...
    'packageRoot',packageRoot, ...
    'models',fullfile(packageRoot,'models'), ...
    'results',fullfile(packageRoot,'results'), ...
    'figures',fullfile(packageRoot,'results','figures'), ...
    'tables',fullfile(packageRoot,'results','tables'), ...
    'reports',fullfile(packageRoot,'results','reports'), ...
    'runtime',runtimeRoot, ...
    'cache',fullfile(runtimeRoot,'cache'), ...
    'codegen',fullfile(runtimeRoot,'codegen'), ...
    'modelBuild',fullfile(runtimeRoot,'model-build'));

folderNames = {'models','figures','tables','reports','modelBuild'};
for folderIndex = 1:numel(folderNames)
    folder = paths.(folderNames{folderIndex});
    if ~isfolder(folder), mkdir(folder); end
end
end
