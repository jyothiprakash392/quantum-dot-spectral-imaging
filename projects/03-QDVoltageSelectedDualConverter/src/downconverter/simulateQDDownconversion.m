function observation = simulateQDDownconversion(incidentPhotonsPerBin, ...
    selectorVoltage_V,config,varargin)
%SIMULATEQDDOWNCONVERSION UV -> selected QD film -> VIS/NIR detector model.
%   O = SIMULATEQDDOWNCONVERSION(U,V,CONFIG) applies the passive film-bank
%   operator selected by voltage V, synthesizes the emitted spectrum, and
%   models the split silicon-CCD/InGaAs detector.
%
%   Name-value options:
%     AddNoise          true by default
%     Seed              local deterministic random-stream seed
%     EnforceFullWell   clip detector bins at full well (default true)
%     ReconstructSpectrum  solve for the incident UV spectrum (default false)
%
%   The global MATLAB random-number state is never modified.

if nargin<3 || isempty(config)
    config = qdDownconversionConfig();
end
if nargin<2 || isempty(selectorVoltage_V)
    selectorVoltage_V = config.selector.defaultVoltage_V;
end
response = qdBuildDownconversionResponse(config,selectorVoltage_V);

parser = inputParser;
parser.FunctionName = 'simulateQDDownconversion';
addParameter(parser,'AddNoise',true, ...
    @(x)(islogical(x)||isnumeric(x))&&isscalar(x)&&isfinite(x));
addParameter(parser,'Seed',config.randomSeed, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&& ...
    x==fix(x)&&x>=0);
addParameter(parser,'EnforceFullWell',true, ...
    @(x)(islogical(x)||isnumeric(x))&&isscalar(x)&&isfinite(x));
addParameter(parser,'ReconstructSpectrum',false, ...
    @(x)(islogical(x)||isnumeric(x))&&isscalar(x)&&isfinite(x));
parse(parser,varargin{:});
options = parser.Results;

incident = incidentPhotonsPerBin(:);
if ~isnumeric(incidentPhotonsPerBin) || ~isreal(incidentPhotonsPerBin) || ...
        numel(incident)~=numel(config.inputWavelength_nm) || ...
        any(~isfinite(incident)) || any(incident<0)
    error('QDConverter:IncidentSpectrum', ...
        'Incident UV spectrum must contain one finite nonnegative count per bin.');
end

channelPhotons = ...
    response.converterResponse_photonsPerIncidentPhoton*incident;
outputSpectrum = response.emissionBasis_perBin*channelPhotons;
siElectronsExpected = ...
    response.siDetectionGain_electronsPerPhoton.*outputSpectrum;
ingaasElectronsExpected = ...
    response.ingaasDetectionGain_electronsPerPhoton.*outputSpectrum;
signalElectronsExpected = siElectronsExpected+ingaasElectronsExpected;
darkElectronsExpected = response.detectorDarkElectrons;
totalElectronsExpected = signalElectronsExpected+darkElectronsExpected;
noiseVariance = totalElectronsExpected+response.readNoiseElectronsRMS.^2;

if logical(options.AddNoise)
    stream = RandStream('mt19937ar','Seed',double(options.Seed));
    measuredElectrons = localPoissonVector(totalElectronsExpected,stream)+ ...
        response.readNoiseElectronsRMS.*randn(stream,size(totalElectronsExpected));
else
    measuredElectrons = totalElectronsExpected;
end
measuredElectrons = max(0,measuredElectrons);
preClipElectrons = measuredElectrons;
if logical(options.EnforceFullWell)
    measuredElectrons = min(measuredElectrons,response.fullWellElectrons);
end
saturated = preClipElectrons>response.fullWellElectrons;

computationalSignalExpected = ...
    response.computational.systemMatrix_electronsPerIncidentPhoton*incident;
computationalDarkExpected = response.computational.darkElectronsExpected;
computationalTotalExpected = computationalSignalExpected+ ...
    computationalDarkExpected;
computationalNoiseVariance = computationalTotalExpected+ ...
    response.computational.readNoiseElectronsRMS.^2;
if logical(options.AddNoise)
    computationalStream = RandStream('mt19937ar', ...
        'Seed',double(options.Seed)+104729);
    computationalMeasured = localPoissonVector( ...
        computationalTotalExpected,computationalStream)+ ...
        response.computational.readNoiseElectronsRMS.* ...
        randn(computationalStream,size(computationalTotalExpected));
else
    computationalMeasured = computationalTotalExpected;
end
computationalMeasured = max(0,computationalMeasured);
computationalPreClip = computationalMeasured;
if logical(options.EnforceFullWell)
    computationalMeasured = min(computationalMeasured, ...
        response.computational.fullWellElectrons);
end
computationalSaturated = computationalPreClip> ...
    response.computational.fullWellElectrons;

hc_Jm = 6.62607015e-34*299792458;
inputEnergyPerPhoton_J = hc_Jm./(config.inputWavelength_nm(:)*1e-9);
outputEnergyPerPhoton_J = hc_Jm./(config.outputWavelength_nm(:)*1e-9);
incidentEnergy_J = sum(incident.*inputEnergyPerPhoton_J);
outputEnergy_J = sum(outputSpectrum.*outputEnergyPerPhoton_J);
absorbedPhotons = sum(response.absorptionProbabilityByInput.*incident);
totalIncidentPhotons = sum(incident);
totalOutputPhotons = sum(outputSpectrum);
photonYield = totalOutputPhotons/max(totalIncidentPhotons,realmin);
absorbedPhotonYield = totalOutputPhotons/max(absorbedPhotons,realmin);
energyEfficiency = outputEnergy_J/max(incidentEnergy_J,realmin);

if any(outputSpectrum>0)
    [~,peakIndex] = max(outputSpectrum);
    peakWavelength_nm = config.outputWavelength_nm(peakIndex);
    centroidWavelength_nm = sum(config.outputWavelength_nm(:).*outputSpectrum)/ ...
        sum(outputSpectrum);
else
    peakWavelength_nm = NaN;
    centroidWavelength_nm = NaN;
end

observation = struct();
observation.schemaVersion = config.schemaVersion;
observation.config = config;
observation.response = response;
observation.control = struct( ...
    'selectorVoltage_V',selectorVoltage_V, ...
    'selectorWeights',response.selectorWeights, ...
    'selectedFilmIndex',response.selectedFilmIndex, ...
    'selectedMaterial',response.selectedMaterial, ...
    'voltageMeaning',config.selector.physicalMeaning);
observation.input = struct( ...
    'wavelength_nm',config.inputWavelength_nm, ...
    'incidentPhotonsPerBin',incident, ...
    'totalIncidentPhotons',totalIncidentPhotons, ...
    'absorbedPhotonsExpected',absorbedPhotons, ...
    'incidentEnergy_J',incidentEnergy_J, ...
    'definition',config.inputDefinition);
observation.conversion = struct( ...
    'channelPhotonCountExpected',channelPhotons, ...
    'outputWavelength_nm',config.outputWavelength_nm, ...
    'outputSpectrumPhotonCountExpectedPerBin',outputSpectrum, ...
    'totalOutputPhotons',totalOutputPhotons, ...
    'peakWavelength_nm',peakWavelength_nm, ...
    'centroidWavelength_nm',centroidWavelength_nm, ...
    'photonYieldPerIncidentPhoton',photonYield, ...
    'photonYieldPerAbsorbedPhoton',absorbedPhotonYield, ...
    'outputEnergy_J',outputEnergy_J, ...
    'opticalEnergyEfficiency',energyEfficiency, ...
    'mechanism',['passive one-photon photoluminescent down-conversion in ' ...
        'a voltage-selected fixed-emission film']);
observation.detector = struct( ...
    'siElectronsExpected',siElectronsExpected, ...
    'ingaasElectronsExpected',ingaasElectronsExpected, ...
    'signalElectronsExpected',signalElectronsExpected, ...
    'darkElectronsExpected',darkElectronsExpected, ...
    'totalElectronsExpected',totalElectronsExpected, ...
    'noiseVariance_e2',noiseVariance, ...
    'readNoiseElectronsRMS',response.readNoiseElectronsRMS, ...
    'measuredElectrons',measuredElectrons, ...
    'preClipElectrons',preClipElectrons, ...
    'saturated',saturated, ...
    'fullWellElectrons',response.fullWellElectrons, ...
    'addNoise',logical(options.AddNoise), ...
    'seed',double(options.Seed));
observation.computationalCCD = struct( ...
    'measurementDefinition',config.spectrometer.inputDefinition, ...
    'signalElectronsExpected',computationalSignalExpected, ...
    'darkElectronsExpected',computationalDarkExpected, ...
    'totalElectronsExpected',computationalTotalExpected, ...
    'noiseVariance_e2',computationalNoiseVariance, ...
    'readNoiseElectronsRMS', ...
        response.computational.readNoiseElectronsRMS, ...
    'measuredElectrons',computationalMeasured, ...
    'preClipElectrons',computationalPreClip, ...
    'saturated',computationalSaturated, ...
    'fullWellElectrons',response.computational.fullWellElectrons);
if logical(options.ReconstructSpectrum)
    observation.reconstruction = reconstructQDSpectrum( ...
        computationalMeasured,response, ...
        'NoiseVariance',computationalNoiseVariance, ...
        'Regularization', ...
            config.spectrometer.reconstructionRegularization, ...
        'MaxIterations',config.spectrometer.reconstructionMaxIterations);
else
    observation.reconstruction = [];
end
observation.validity = struct( ...
    'passiveEnergyConservation',energyEfficiency<=1+128*eps, ...
    'singlePhotonYieldAtMostOne',photonYield<=1+128*eps, ...
    'emissionLongerThanInputBand', ...
        min(config.film.emissionCenter_nm)>max(config.inputWavelength_nm), ...
    'selectorIsDiscreteFilmCommand',true, ...
    'responseMatrixMeasured',response.isMeasuredCalibration, ...
    'calibrationLabel',response.calibrationLabel, ...
    'quantitativeHardwarePrediction', ...
        config.validity.quantitativeHardwarePrediction, ...
    'computationalResponseFullColumnRank', ...
        response.numericalRank==numel(config.inputWavelength_nm), ...
    'anyDetectorSaturation',any(saturated), ...
    'anyComputationalCCDSaturation',any(computationalSaturated));
end

function samples = localPoissonVector(lambda,stream)
% Exact inversion for small means and PTRS transformed rejection otherwise.
samples = zeros(size(lambda));
for index = 1:numel(lambda)
    meanValue = lambda(index);
    if meanValue<=0
        samples(index) = 0;
    elseif meanValue<30
        threshold = exp(-meanValue);
        product = 1;
        count = 0;
        while product>threshold
            count = count+1;
            product = product*rand(stream);
        end
        samples(index) = count-1;
    else
        squareRoot = sqrt(meanValue);
        b = 0.931+2.53*squareRoot;
        a = -0.059+0.02483*b;
        inverseAlpha = 1.1239+1.1328/(b-3.4);
        vLimit = 0.9277-3.6224/(b-2);
        accepted = false;
        while ~accepted
            u = rand(stream)-0.5;
            v = rand(stream);
            uSmall = 0.5-abs(u);
            candidate = floor((2*a/uSmall+b)*u+meanValue+0.43);
            if uSmall>=0.07 && v<=vLimit
                accepted = candidate>=0;
            elseif candidate>=0 && ~(uSmall<0.013 && v>uSmall)
                logarithmicTest = log(v*inverseAlpha/ ...
                    (a/(uSmall*uSmall)+b));
                accepted = logarithmicTest<= ...
                    -meanValue+candidate*log(meanValue)-gammaln(candidate+1);
            end
        end
        samples(index) = candidate;
    end
end
end
