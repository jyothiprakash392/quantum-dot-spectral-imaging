function modelFile = buildQDVoltageSelectedDualConverter(forceRebuild)
%BUILDQDVOLTAGESELECTEDDUALCONVERTER Build the combined conversion model.
%   Mode 0 routes the existing powered SWIR-to-visible converter. Mode 1
%   routes the passive, electronically selected UV-to-visible/NIR converter.

if nargin<1
    forceRebuild = false;
end
builderFolder = fileparts(mfilename('fullpath'));
packageRoot = fileparts(builderFolder);
addpath(packageRoot);
paths = setupQDVoltageSelectedDualConverter();
[~,downConfig] = initQDVoltageSelectedDualConverter(false);
modelName = 'QDVoltageSelectedDualConverter';
modelFile = fullfile(paths.models,[modelName '.slx']);
stagingFile = fullfile(paths.modelBuild,[modelName '.slx']);

if bdIsLoaded(modelName)
    close_system(modelName,0);
end
if isfile(modelFile) && ~forceRebuild
    return
end
if isfile(stagingFile)
    delete(stagingFile);
end

shadowState = warning('query','Simulink:Engine:MdlFileShadowing');
warning('off','Simulink:Engine:MdlFileShadowing');
cleanup = onCleanup(@()warning(shadowState.state, ...
    'Simulink:Engine:MdlFileShadowing'));
new_system(modelName);
clear cleanup
set_param(modelName, ...
    'SolverType','Fixed-step', ...
    'Solver','FixedStepDiscrete', ...
    'FixedStep','1', ...
    'StartTime','0', ...
    'StopTime','0', ...
    'SignalLogging','on', ...
    'SignalLoggingName','logsout', ...
    'ReturnWorkspaceOutputs','on', ...
    'InitFcn',localInitCommand('initQDVoltageSelectedDualConverter'), ...
    'Description',['Attached dual-path quantum-dot conversion system: ' ...
        'powered SWIR-to-visible up-conversion or passive electronically ' ...
        'selected UV-to-visible/NIR down-conversion, with detector and ' ...
        'computation.'], ...
    'ModelVersionFormat','1.0', ...
    'ModelBrowserVisibility','off');

% Powered SWIR-to-visible branch retained from the validated model.
add_block('simulink/Sources/Constant',[modelName '/Incoming SWIR Spectrum'], ...
    'Value','qdIncidentSpectrum','SampleTime','inf', ...
    'Position',[35 70 210 110]);
add_block('simulink/Math Operations/Gain', ...
    [modelName '/Powered SWIR-to-Visible QD Converter'], ...
    'Gain',['qdSpectrometerResponse.' ...
        'converterResponse_photonsPerIncidentPhoton'], ...
    'Multiplication','Matrix(K*u)','Position',[285 45 555 115]);
add_line(modelName,'Incoming SWIR Spectrum/1', ...
    'Powered SWIR-to-Visible QD Converter/1','autorouting','on');
add_block('simulink/Math Operations/Gain', ...
    [modelName '/Upconverted Visible Spectrum'], ...
    'Gain','qdSpectrometerResponse.visibleEmissionBasis_perBin', ...
    'Multiplication','Matrix(K*u)','Position',[625 25 825 75]);
add_line(modelName,'Powered SWIR-to-Visible QD Converter/1', ...
    'Upconverted Visible Spectrum/1','autorouting','on');
add_block('simulink/Math Operations/Gain', ...
    [modelName '/Map Upconversion to Common Grid'], ...
    'Gain','qdUpToCommonMatrix','Multiplication','Matrix(K*u)', ...
    'Position',[885 25 1085 75]);
add_line(modelName,'Upconverted Visible Spectrum/1', ...
    'Map Upconversion to Common Grid/1','autorouting','on');

add_block('simulink/Math Operations/Gain',[modelName '/Upconversion CCD'], ...
    'Gain',['diag(qdSpectrometerResponse.' ...
        'ccdDetectionGain_electronsPerVisiblePhoton)'], ...
    'Multiplication','Matrix(K*u)','Position',[625 105 825 155]);
add_line(modelName,'Powered SWIR-to-Visible QD Converter/1', ...
    'Upconversion CCD/1','autorouting','on');
add_block('simulink/Sources/Constant',[modelName '/Up CCD Dark'], ...
    'Value','qdCCDdarkElectrons','SampleTime','inf', ...
    'Position',[625 175 775 210]);
add_block('simulink/Math Operations/Sum',[modelName '/Up CCD Readout'], ...
    'Inputs','++','Position',[880 112 915 165]);
add_line(modelName,'Upconversion CCD/1','Up CCD Readout/1','autorouting','on');
add_line(modelName,'Up CCD Dark/1','Up CCD Readout/2','autorouting','on');
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/SWIR Reconstruction'], ...
    'FunctionName','qdSpectralReconstructionSFunction', ...
    'Position',[985 105 1195 170]);
add_line(modelName,'Up CCD Readout/1','SWIR Reconstruction/1', ...
    'autorouting','on');

% Passive UV-to-visible/NIR branch controlled by an electronic decoder.
add_block('simulink/Sources/Constant',[modelName '/Incoming UV Spectrum'], ...
    'Value','qdUVIncidentSpectrum','SampleTime','inf', ...
    'Position',[35 335 210 375]);
add_block('simulink/Sources/Constant',[modelName '/Electronic Selector Voltage'], ...
    'Value',num2str(downConfig.selector.defaultVoltage_V,15), ...
    'SampleTime','inf', ...
    'Position',[35 430 210 470]);
decoderPath = [modelName '/ADC Window Decoder + Gate Driver'];
localAddElectronicDecoder(decoderPath,[285 455 555 565]);
add_line(modelName,'Electronic Selector Voltage/1', ...
    'ADC Window Decoder + Gate Driver/1','autorouting','on');
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/Passive UV-to-NIR QD Film Bank'], ...
    'FunctionName','qdDownconversionSFunction', ...
    'Position',[285 300 555 440]);
add_line(modelName,'Incoming UV Spectrum/1', ...
    'Passive UV-to-NIR QD Film Bank/1','autorouting','on');
add_line(modelName,'ADC Window Decoder + Gate Driver/1', ...
    'Passive UV-to-NIR QD Film Bank/2','autorouting','on');
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/UV Reconstruction'], ...
    'FunctionName','qdDownconversionReconstructionSFunction', ...
    'Position',[625 355 840 425]);
add_line(modelName,'Passive UV-to-NIR QD Film Bank/2', ...
    'UV Reconstruction/1','autorouting','on');
add_line(modelName,'ADC Window Decoder + Gate Driver/1', ...
    'UV Reconstruction/2','autorouting','on');

% Optical path selection and shared hybrid detector.
add_block('simulink/Sources/Constant',[modelName '/Conversion Mode'], ...
    'Value','1','SampleTime','inf', ...
    'Position',[885 430 1045 470]);
add_block('simulink/Signal Routing/Switch',[modelName '/Optical Path Selector'], ...
    'Criteria','u2 >= Threshold','Threshold','0.5', ...
    'Position',[1170 260 1225 360]);
add_line(modelName,'Passive UV-to-NIR QD Film Bank/1', ...
    'Optical Path Selector/1','autorouting','on');
add_line(modelName,'Conversion Mode/1','Optical Path Selector/2', ...
    'autorouting','on');
add_line(modelName,'Map Upconversion to Common Grid/1', ...
    'Optical Path Selector/3','autorouting','on');

detectorPath = [modelName '/Shared Si CCD + InGaAs Detector'];
localBuildHybridDetector(detectorPath,[1315 245 1565 365]);
add_line(modelName,'Optical Path Selector/1', ...
    'Shared Si CCD + InGaAs Detector/1','autorouting','on');
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/Selected Output Computation'], ...
    'FunctionName','qdSpectralTelemetrySFunction', ...
    'Position',[1645 255 1855 345]);
add_line(modelName,'Optical Path Selector/1', ...
    'Selected Output Computation/1','autorouting','on');
add_line(modelName,'Shared Si CCD + InGaAs Detector/3', ...
    'Selected Output Computation/2','autorouting','on');

localAddWorkspaceSink(modelName,'Selected Optical Output to Workspace', ...
    'qdDualSelectedSpectrumSim',[1290 415 1515 450]);
add_line(modelName,'Optical Path Selector/1', ...
    'Selected Optical Output to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Selected Detector to Workspace', ...
    'qdDualDetectorSim',[1605 395 1810 430]);
add_line(modelName,'Shared Si CCD + InGaAs Detector/3', ...
    'Selected Detector to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'SWIR Reconstruction to Workspace', ...
    'qdDualSWIRReconstructionSim',[1255 105 1485 140]);
add_line(modelName,'SWIR Reconstruction/1', ...
    'SWIR Reconstruction to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'UV Reconstruction to Workspace', ...
    'qdDualUVReconstructionSim',[890 365 1105 400]);
add_line(modelName,'UV Reconstruction/1', ...
    'UV Reconstruction to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Film Control to Workspace', ...
    'qdDualFilmControlSim',[605 475 805 510]);
add_line(modelName,'Passive UV-to-NIR QD Film Bank/3', ...
    'Film Control to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Electronic Gates to Workspace', ...
    'qdDualElectronicGatesSim',[605 535 820 570]);
add_line(modelName,'ADC Window Decoder + Gate Driver/2', ...
    'Electronic Gates to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Decoder Telemetry to Workspace', ...
    'qdDualDecoderTelemetrySim',[605 590 830 625]);
add_line(modelName,'ADC Window Decoder + Gate Driver/3', ...
    'Decoder Telemetry to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Selected Metrics to Workspace', ...
    'qdDualMetricsSim',[1905 280 2095 315]);
add_line(modelName,'Selected Output Computation/1', ...
    'Selected Metrics to Workspace/1','autorouting','on');

localAddSelectorSlider(modelName,downConfig,[35 500 255 555]);
localAddModeSwitch(modelName,[900 520 1035 595]);
Simulink.Annotation(modelName,sprintf([ ...
    'QD VOLTAGE-SELECTED DUAL CONVERTER\n' ...
    'MODE 0: powered SWIR -> visible conversion -> silicon CCD -> SWIR reconstruction.\n' ...
    'MODE 1: passive UV -> electronically selected VIS/NIR channel -> Si/InGaAs detection -> UV reconstruction.\n' ...
    'An explicit 12-bit ADC/window decoder drives a 1-of-6 solid-state optical gate command with hysteresis.\n' ...
    'The voltage selects fixed films; it does not broadly tune one passive QD material.\n' ...
    'UNMEASURED SYNTHETIC DEFAULT: calibrate both branches before quantitative hardware use.']));

set_param(modelName,'ZoomFactor','FitSystem');
save_system(modelName,stagingFile);
set_param(modelName,'SimulationCommand','update');
save_system(modelName,stagingFile);
close_system(modelName,0);
movefile(stagingFile,modelFile,'f');
end

function command = localInitCommand(initializer)
command = [ ...
    'qdPackageRoot=fileparts(fileparts(get_param(bdroot,''FileName'')));' ...
    'addpath(qdPackageRoot);setupQDVoltageSelectedDualConverter();' ...
    initializer '(false);clear qdPackageRoot;'];
end

function localAddElectronicDecoder(decoderPath,position)
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    decoderPath,'FunctionName','qdElectronicSelectorDecoderSFunction', ...
    'Position',position);
mask = Simulink.Mask.create(decoderPath);
mask.Description = ['Electronic selector: ADC quantization, voltage-window ' ...
    'decoding, comparator hysteresis, and one-hot optical-gate command.'];
mask.Display = sprintf([ ...
    'disp(''12-bit ADC + WINDOW DECODER'');\n' ...
    'port_label(''input'',1,''Vselect'');\n' ...
    'port_label(''output'',1,''Vchannel'');\n' ...
    'port_label(''output'',2,''1-of-6 gates'');\n' ...
    'port_label(''output'',3,''telemetry'');']);
end

function localBuildHybridDetector(detectorPath,position)
add_block('simulink/Ports & Subsystems/Subsystem',detectorPath, ...
    'Position',position);
Simulink.SubSystem.deleteContents(detectorPath);
add_block('simulink/Ports & Subsystems/In1',[detectorPath '/Photons'], ...
    'PortDimensions','numel(qdCommonOutputWavelength_nm)', ...
    'Position',[25 63 55 77]);
add_block('simulink/Math Operations/Gain',[detectorPath '/Silicon CCD'], ...
    'Gain','diag(qdSiDetectorGain_ePerPhoton)', ...
    'Multiplication','Matrix(K*u)','Position',[100 20 245 60]);
add_block('simulink/Math Operations/Gain',[detectorPath '/InGaAs Array'], ...
    'Gain','diag(qdInGaAsDetectorGain_ePerPhoton)', ...
    'Multiplication','Matrix(K*u)','Position',[100 100 245 140]);
add_block('simulink/Math Operations/Sum',[detectorPath '/Dichroic sum'], ...
    'Inputs','++','Position',[300 55 330 95]);
add_block('simulink/Ports & Subsystems/Out1',[detectorPath '/Si'], ...
    'PortDimensions','numel(qdCommonOutputWavelength_nm)', ...
    'Position',[390 28 420 42]);
add_block('simulink/Ports & Subsystems/Out1',[detectorPath '/InGaAs'], ...
    'Port','2','PortDimensions','numel(qdCommonOutputWavelength_nm)', ...
    'Position',[390 112 420 126]);
add_block('simulink/Ports & Subsystems/Out1',[detectorPath '/Hybrid'], ...
    'Port','3','PortDimensions','numel(qdCommonOutputWavelength_nm)', ...
    'Position',[390 70 420 84]);
add_line(detectorPath,'Photons/1','Silicon CCD/1','autorouting','on');
add_line(detectorPath,'Photons/1','InGaAs Array/1','autorouting','on');
add_line(detectorPath,'Silicon CCD/1','Dichroic sum/1','autorouting','on');
add_line(detectorPath,'InGaAs Array/1','Dichroic sum/2','autorouting','on');
add_line(detectorPath,'Silicon CCD/1','Si/1','autorouting','on');
add_line(detectorPath,'InGaAs Array/1','InGaAs/1','autorouting','on');
add_line(detectorPath,'Dichroic sum/1','Hybrid/1','autorouting','on');
mask = Simulink.Mask.create(detectorPath);
mask.Description = ['Dichroic split between a silicon CCD and an InGaAs ' ...
    'array so the combined output grid is not limited by silicon cutoff.'];
mask.Display = sprintf([ ...
    'disp(''SHARED Si + InGaAs'');\n' ...
    'port_label(''input'',1,''VIS/NIR'');\n' ...
    'port_label(''output'',1,''Si'');\n' ...
    'port_label(''output'',2,''InGaAs'');\n' ...
    'port_label(''output'',3,''hybrid'');']);
end

function localAddSelectorSlider(modelName,config,position)
sliderPath = [modelName '/Selector Voltage Slider'];
channelVoltages = config.selector.channelVoltage_V(:);
tickInterval = min(diff(channelVoltages));
add_block('simulink_hmi_blocks/Slider',sliderPath,'Position',position);
set_param(sliderPath,'Limits',[channelVoltages(1) tickInterval ...
    channelVoltages(end)],'ScaleType','Linear');
source = Simulink.HMI.ParamSourceInfo;
source.BlockPath = Simulink.BlockPath( ...
    [modelName '/Electronic Selector Voltage']);
source.ParamName = 'Value';
set_param(sliderPath,'Binding',source);
end

function localAddModeSwitch(modelName,position)
switchPath = [modelName '/Conversion Mode Switch'];
add_block('simulink_hmi_blocks/Toggle Switch',switchPath, ...
    'Position',position);
states = struct('Value',{0;1}, ...
    'Label',{'0: SWIR UP';'1: UV DOWN'});
set_param(switchPath,'States',states);
source = Simulink.HMI.ParamSourceInfo;
source.BlockPath = Simulink.BlockPath([modelName '/Conversion Mode']);
source.ParamName = 'Value';
set_param(switchPath,'Binding',source);
end

function localAddWorkspaceSink(modelName,blockName,variableName,position)
add_block('simulink/Sinks/To Workspace',[modelName '/' blockName], ...
    'VariableName',variableName,'SaveFormat','Structure With Time', ...
    'MaxDataPoints','inf','Position',position);
end
