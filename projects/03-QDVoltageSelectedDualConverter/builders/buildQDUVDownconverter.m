function modelFile = buildQDUVDownconverter(forceRebuild)
%BUILDQDUVDOWNCONVERTER Build the passive UV-to-visible/NIR model.

if nargin<1
    forceRebuild = false;
end
builderFolder = fileparts(mfilename('fullpath'));
packageRoot = fileparts(builderFolder);
addpath(packageRoot);
paths = setupQDVoltageSelectedDualConverter();
[downConfig,~] = initQDUVDownconverter(false);
modelName = 'QDUVDownconverter';
modelFile = fullfile(paths.models,[modelName '.slx']);
stagingFile = fullfile(paths.modelBuild,[modelName '.slx']);

if bdIsLoaded(modelName)
    close_system(modelName,0);
end
if isfile(modelFile) && ~forceRebuild
    return
end
if isfile(stagingFile)
    delete(stagingFile);
end

shadowState = warning('query','Simulink:Engine:MdlFileShadowing');
warning('off','Simulink:Engine:MdlFileShadowing');
cleanup = onCleanup(@()warning(shadowState.state, ...
    'Simulink:Engine:MdlFileShadowing'));
new_system(modelName);
clear cleanup
set_param(modelName, ...
    'SolverType','Fixed-step', ...
    'Solver','FixedStepDiscrete', ...
    'FixedStep','1', ...
    'StartTime','0', ...
    'StopTime','0', ...
    'SignalLogging','on', ...
    'SignalLoggingName','logsout', ...
    'ReturnWorkspaceOutputs','on', ...
    'InitFcn',localInitCommand('initQDUVDownconverter'), ...
    'Description',['Passive UV-to-visible/NIR QD film bank selected by an ' ...
        'electronic voltage decoder, split silicon/InGaAs detection, and ' ...
        'UV spectral reconstruction from spatial filter measurements.'], ...
    'ModelVersionFormat','1.0', ...
    'ModelBrowserVisibility','off');

add_block('simulink/Sources/Constant',[modelName '/Incoming UV Spectrum'], ...
    'Value','qdUVIncidentSpectrum','SampleTime','inf', ...
    'Position',[35 160 210 205]);
add_block('simulink/Sources/Constant',[modelName '/Electronic Selector Voltage'], ...
    'Value',num2str(downConfig.selector.defaultVoltage_V,15), ...
    'SampleTime','inf', ...
    'Position',[35 285 210 325]);
decoderPath = [modelName '/ADC Window Decoder + Gate Driver'];
localAddElectronicDecoder(decoderPath,[310 290 595 405]);
add_line(modelName,'Electronic Selector Voltage/1', ...
    'ADC Window Decoder + Gate Driver/1','autorouting','on');

add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/Voltage-Selected Passive QD Film Bank'], ...
    'FunctionName','qdDownconversionSFunction', ...
    'Position',[310 125 595 265]);
add_line(modelName,'Incoming UV Spectrum/1', ...
    'Voltage-Selected Passive QD Film Bank/1','autorouting','on');
add_line(modelName,'ADC Window Decoder + Gate Driver/1', ...
    'Voltage-Selected Passive QD Film Bank/2','autorouting','on');

detectorPath = [modelName '/Dichroic Si CCD + InGaAs Detector'];
localBuildHybridDetector(detectorPath,[715 85 985 245]);
add_line(modelName,'Voltage-Selected Passive QD Film Bank/1', ...
    'Dichroic Si CCD + InGaAs Detector/1','autorouting','on');

add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/Nonnegative UV Reconstruction'], ...
    'FunctionName','qdDownconversionReconstructionSFunction', ...
    'Position',[715 300 985 390]);
add_line(modelName,'Voltage-Selected Passive QD Film Bank/2', ...
    'Nonnegative UV Reconstruction/1','autorouting','on');
add_line(modelName,'ADC Window Decoder + Gate Driver/1', ...
    'Nonnegative UV Reconstruction/2','autorouting','on');

add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/Output Spectrum Computation'], ...
    'FunctionName','qdSpectralTelemetrySFunction', ...
    'Position',[1080 125 1305 215]);
add_line(modelName,'Voltage-Selected Passive QD Film Bank/1', ...
    'Output Spectrum Computation/1','autorouting','on');
add_line(modelName,'Dichroic Si CCD + InGaAs Detector/3', ...
    'Output Spectrum Computation/2','autorouting','on');

localAddWorkspaceSink(modelName,'UV Input to Workspace','qdUVInputSim', ...
    [245 455 430 490]);
add_line(modelName,'Incoming UV Spectrum/1', ...
    'UV Input to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Output Spectrum to Workspace', ...
    'qdDownOutputSpectrumSim',[720 20 930 55]);
add_line(modelName,'Voltage-Selected Passive QD Film Bank/1', ...
    'Output Spectrum to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Computational CCD to Workspace', ...
    'qdDownCCDMeasurementSim',[710 450 930 485]);
add_line(modelName,'Voltage-Selected Passive QD Film Bank/2', ...
    'Computational CCD to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Film Control to Workspace', ...
    'qdDownFilmControlSim',[705 510 915 545]);
add_line(modelName,'Voltage-Selected Passive QD Film Bank/3', ...
    'Film Control to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Electronic Gates to Workspace', ...
    'qdDownElectronicGatesSim',[270 575 485 610]);
add_line(modelName,'ADC Window Decoder + Gate Driver/2', ...
    'Electronic Gates to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Decoder Telemetry to Workspace', ...
    'qdDownDecoderTelemetrySim',[705 575 930 610]);
add_line(modelName,'ADC Window Decoder + Gate Driver/3', ...
    'Decoder Telemetry to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Reconstructed UV to Workspace', ...
    'qdDownReconstructedUVSim',[1070 335 1295 370]);
add_line(modelName,'Nonnegative UV Reconstruction/1', ...
    'Reconstructed UV to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Hybrid Detector to Workspace', ...
    'qdDownHybridDetectorSim',[1060 255 1280 290]);
add_line(modelName,'Dichroic Si CCD + InGaAs Detector/3', ...
    'Hybrid Detector to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Output Metrics to Workspace', ...
    'qdDownOutputMetricsSim',[1375 150 1580 185]);
add_line(modelName,'Output Spectrum Computation/1', ...
    'Output Metrics to Workspace/1','autorouting','on');

localAddSelectorSlider(modelName,downConfig);
Simulink.Annotation(modelName,sprintf([ ...
    'VOLTAGE-SELECTED QD UV -> VISIBLE/NIR DOWNCONVERTER\n' ...
    'A scalar voltage is decoded electronically to select one fixed-emission channel (470 to 1410 nm); no rotor is used.\n' ...
    'The explicit 12-bit ADC/window-decoder block emits a 1-of-6 solid-state gate command with hysteresis.\n' ...
    'A 12-pixel x 5-bias UV filter array preserves spatial measurements for spectral reconstruction.\n' ...
    'Silicon CCD is used below the dichroic crossover; InGaAs handles the longer NIR bands.\n' ...
    'UNMEASURED SYNTHETIC DEFAULT: replace film, filter, detector, and noise curves with calibration data.']));

set_param(modelName,'ZoomFactor','FitSystem');
save_system(modelName,stagingFile);
set_param(modelName,'SimulationCommand','update');
save_system(modelName,stagingFile);
close_system(modelName,0);
movefile(stagingFile,modelFile,'f');
end

function command = localInitCommand(initializer)
command = [ ...
    'qdPackageRoot=fileparts(fileparts(get_param(bdroot,''FileName'')));' ...
    'addpath(qdPackageRoot);setupQDVoltageSelectedDualConverter();' ...
    initializer '(false);clear qdPackageRoot;'];
end

function localAddElectronicDecoder(decoderPath,position)
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    decoderPath,'FunctionName','qdElectronicSelectorDecoderSFunction', ...
    'Position',position);
mask = Simulink.Mask.create(decoderPath);
mask.Description = ['Electronic selector: ADC quantization, voltage-window ' ...
    'decoding, comparator hysteresis, and one-hot optical-gate command.'];
mask.Display = sprintf([ ...
    'disp(''12-bit ADC + WINDOW DECODER'');\n' ...
    'port_label(''input'',1,''Vselect'');\n' ...
    'port_label(''output'',1,''Vchannel'');\n' ...
    'port_label(''output'',2,''1-of-6 gates'');\n' ...
    'port_label(''output'',3,''telemetry'');']);
end

function localBuildHybridDetector(detectorPath,position)
add_block('simulink/Ports & Subsystems/Subsystem',detectorPath, ...
    'Position',position);
Simulink.SubSystem.deleteContents(detectorPath);
add_block('simulink/Ports & Subsystems/In1',[detectorPath '/Output photons'], ...
    'PortDimensions','numel(qdCommonOutputWavelength_nm)', ...
    'Position',[25 78 55 92]);
add_block('simulink/Math Operations/Gain',[detectorPath '/Silicon CCD QE'], ...
    'Gain','diag(qdSiDetectorGain_ePerPhoton)', ...
    'Multiplication','Matrix(K*u)','Position',[105 28 270 72]);
add_block('simulink/Math Operations/Gain',[detectorPath '/InGaAs QE'], ...
    'Gain','diag(qdInGaAsDetectorGain_ePerPhoton)', ...
    'Multiplication','Matrix(K*u)','Position',[105 112 270 156]);
add_block('simulink/Math Operations/Sum',[detectorPath '/Hybrid sum'], ...
    'Inputs','++','Position',[325 72 355 112]);
add_block('simulink/Ports & Subsystems/Out1',[detectorPath '/Si electrons'], ...
    'PortDimensions','numel(qdCommonOutputWavelength_nm)', ...
    'Position',[425 38 455 52]);
add_block('simulink/Ports & Subsystems/Out1',[detectorPath '/InGaAs electrons'], ...
    'Port','2','PortDimensions','numel(qdCommonOutputWavelength_nm)', ...
    'Position',[425 130 455 144]);
add_block('simulink/Ports & Subsystems/Out1',[detectorPath '/Hybrid electrons'], ...
    'Port','3','PortDimensions','numel(qdCommonOutputWavelength_nm)', ...
    'Position',[425 87 455 101]);
add_line(detectorPath,'Output photons/1','Silicon CCD QE/1','autorouting','on');
add_line(detectorPath,'Output photons/1','InGaAs QE/1','autorouting','on');
add_line(detectorPath,'Silicon CCD QE/1','Hybrid sum/1','autorouting','on');
add_line(detectorPath,'InGaAs QE/1','Hybrid sum/2','autorouting','on');
add_line(detectorPath,'Silicon CCD QE/1','Si electrons/1','autorouting','on');
add_line(detectorPath,'InGaAs QE/1','InGaAs electrons/1','autorouting','on');
add_line(detectorPath,'Hybrid sum/1','Hybrid electrons/1','autorouting','on');
mask = Simulink.Mask.create(detectorPath);
mask.Description = ['Dichroic split detector: silicon CCD for visible/NIR-I ' ...
    'and InGaAs for wavelengths beyond the silicon cutoff.'];
mask.Display = sprintf([ ...
    'disp(''DICHROIC DETECTOR'');\n' ...
    'port_label(''input'',1,''VIS/NIR'');\n' ...
    'port_label(''output'',1,''Si'');\n' ...
    'port_label(''output'',2,''InGaAs'');\n' ...
    'port_label(''output'',3,''hybrid'');']);
end

function localAddSelectorSlider(modelName,config)
sliderPath = [modelName '/Selector Voltage Slider'];
channelVoltages = config.selector.channelVoltage_V(:);
tickInterval = min(diff(channelVoltages));
add_block('simulink_hmi_blocks/Slider',sliderPath, ...
    'Position',[35 350 245 405]);
set_param(sliderPath,'Limits',[channelVoltages(1) tickInterval ...
    channelVoltages(end)],'ScaleType','Linear');
source = Simulink.HMI.ParamSourceInfo;
source.BlockPath = Simulink.BlockPath( ...
    [modelName '/Electronic Selector Voltage']);
source.ParamName = 'Value';
set_param(sliderPath,'Binding',source);
end

function localAddWorkspaceSink(modelName,blockName,variableName,position)
add_block('simulink/Sinks/To Workspace',[modelName '/' blockName], ...
    'VariableName',variableName,'SaveFormat','Structure With Time', ...
    'MaxDataPoints','inf','Position',position);
end
