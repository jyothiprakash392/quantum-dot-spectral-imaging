function modelFile = buildQDSWIRUpconversionSpectrometer(forceRebuild)
%BUILDQDSWIRUPCONVERSIONSPECTROMETER Build the powered SWIR branch model.

if nargin < 1
    forceRebuild = false;
end
builderFolder = fileparts(mfilename('fullpath'));
packageRoot = fileparts(builderFolder);
addpath(packageRoot);
paths = setupQDVoltageSelectedDualConverter();
initQDSWIRUpconversionSpectrometer(false);
modelName = 'QDSWIRUpconversionSpectrometer';
modelFile = fullfile(paths.models,[modelName '.slx']);
stagingFile = fullfile(paths.modelBuild,[modelName '.slx']);

if bdIsLoaded(modelName)
    close_system(modelName,0);
end
if isfile(modelFile) && ~forceRebuild
    return
end
if isfile(stagingFile)
    delete(stagingFile);
end

% A validated model may already exist while its replacement is staged.
% Suppress only that intentional shadowing diagnostic during new_system.
shadowWarningState = warning('query','Simulink:Engine:MdlFileShadowing');
warning('off','Simulink:Engine:MdlFileShadowing');
warningCleanup = onCleanup(@()warning(shadowWarningState.state, ...
    'Simulink:Engine:MdlFileShadowing'));
new_system(modelName);
clear warningCleanup
set_param(modelName, ...
    'SolverType','Fixed-step', ...
    'Solver','FixedStepDiscrete', ...
    'FixedStep','1', ...
    'StartTime','0', ...
    'StopTime','0', ...
    'SignalLogging','on', ...
    'SignalLoggingName','logsout', ...
    'ReturnWorkspaceOutputs','on', ...
    'InitFcn',localInitCommand('initQDSWIRUpconversionSpectrometer'), ...
    'Description',['Bias-tuned CQD photodiode/QLED wavelength converter, ' ...
        'visible CCD, and nonnegative spectral reconstruction'], ...
    'ModelVersionFormat','1.0', ...
    'ModelBrowserVisibility','off');

add_block('simulink/Sources/Constant',[modelName '/Incoming SWIR Spectrum'], ...
    'Value','qdIncidentSpectrum','SampleTime','inf', ...
    'Position',[35 180 205 225]);

converterPath = [modelName '/CQD IR-to-Visible Converter'];
add_block('simulink/Ports & Subsystems/Subsystem',converterPath, ...
    'Position',[285 120 535 285]);
Simulink.SubSystem.deleteContents(converterPath);
add_block('simulink/Ports & Subsystems/In1',[converterPath '/SWIR photons'], ...
    'PortDimensions','numel(qdSpectrometerConfig.inputWavelength_nm)', ...
    'Position',[25 63 55 77]);
add_block('simulink/Math Operations/Gain',[converterPath '/Bias-tuned PbS response H'], ...
    'Gain',['qdSpectrometerResponse.' ...
        'converterResponse_photonsPerIncidentPhoton'], ...
    'Multiplication','Matrix(K*u)', ...
    'Position',[110 40 345 100]);
add_block('simulink/Ports & Subsystems/Out1',[converterPath '/Visible channel photons'], ...
    'PortDimensions','qdSpectrometerConfig.measurementCount', ...
    'Position',[405 63 435 77]);
add_line(converterPath,'SWIR photons/1','Bias-tuned PbS response H/1', ...
    'autorouting','on');
add_line(converterPath,'Bias-tuned PbS response H/1', ...
    'Visible channel photons/1','autorouting','on');
converterMask = Simulink.Mask.create(converterPath);
converterMask.Description = ['Small-bandgap PbS CQD sensitizer/photodiode ' ...
    'driving a visible CdSe/ZnS QD emitter. Bias supplies the anti-Stokes energy.'];
converterMask.Display = sprintf([ ...
    'disp(''POWERED QD UPCONVERTER'');\n' ...
    'port_label(''input'',1,''SWIR'');\n' ...
    'port_label(''output'',1,''VIS'');']);

add_line(modelName,'Incoming SWIR Spectrum/1', ...
    'CQD IR-to-Visible Converter/1','autorouting','on');

add_block('simulink/Math Operations/Gain', ...
    [modelName '/Visible PL Spectrum Synthesis'], ...
    'Gain','qdSpectrometerResponse.visibleEmissionBasis_perBin', ...
    'Multiplication','Matrix(K*u)', ...
    'Position',[605 35 810 90]);
add_line(modelName,'CQD IR-to-Visible Converter/1', ...
    'Visible PL Spectrum Synthesis/1','autorouting','on');

ccdPath = [modelName '/Visible CCD Array'];
add_block('simulink/Ports & Subsystems/Subsystem',ccdPath, ...
    'Position',[605 145 810 270]);
Simulink.SubSystem.deleteContents(ccdPath);
add_block('simulink/Ports & Subsystems/In1',[ccdPath '/Visible photons'], ...
    'PortDimensions','qdSpectrometerConfig.measurementCount', ...
    'Position',[25 58 55 72]);
add_block('simulink/Math Operations/Gain',[ccdPath '/QE throughput gain'], ...
    'Gain',['diag(qdSpectrometerResponse.' ...
        'ccdDetectionGain_electronsPerVisiblePhoton)'], ...
    'Multiplication','Matrix(K*u)', ...
    'Position',[110 40 285 90]);
add_block('simulink/Ports & Subsystems/Out1',[ccdPath '/Photoelectrons'], ...
    'PortDimensions','qdSpectrometerConfig.measurementCount', ...
    'Position',[345 58 375 72]);
add_line(ccdPath,'Visible photons/1','QE throughput gain/1','autorouting','on');
add_line(ccdPath,'QE throughput gain/1','Photoelectrons/1','autorouting','on');
ccdMask = Simulink.Mask.create(ccdPath);
ccdMask.Description = ['Monochrome silicon CCD quantum efficiency, optical ' ...
    'throughput, and pixel fill factor.'];
ccdMask.Display = sprintf([ ...
    'disp(''SILICON CCD'');\n' ...
    'port_label(''input'',1,''VIS'');\n' ...
    'port_label(''output'',1,''e-'');']);
add_line(modelName,'CQD IR-to-Visible Converter/1','Visible CCD Array/1', ...
    'autorouting','on');

add_block('simulink/Sources/Constant',[modelName '/CCD Dark Offset'], ...
    'Value','qdCCDdarkElectrons','SampleTime','inf', ...
    'Position',[600 310 760 345]);
add_block('simulink/Sources/Constant',[modelName '/CCD Noise Realization'], ...
    'Value','qdCCDNoiseElectrons','SampleTime','inf', ...
    'Position',[600 370 760 405]);
add_block('simulink/Math Operations/Sum',[modelName '/CCD Readout'], ...
    'Inputs','+++','Position',[880 190 915 265]);
add_line(modelName,'Visible CCD Array/1','CCD Readout/1','autorouting','on');
add_line(modelName,'CCD Dark Offset/1','CCD Readout/2','autorouting','on');
add_line(modelName,'CCD Noise Realization/1','CCD Readout/3','autorouting','on');

add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
    [modelName '/Nonnegative Spectral Reconstruction'], ...
    'FunctionName','qdSpectralReconstructionSFunction', ...
    'Position',[1000 180 1255 275]);
add_line(modelName,'CCD Readout/1','Nonnegative Spectral Reconstruction/1', ...
    'autorouting','on');

localAddWorkspaceSink(modelName,'Input Spectrum to Workspace', ...
    'qdInputSpectrumSim',[225 420 430 455]);
add_line(modelName,'Incoming SWIR Spectrum/1', ...
    'Input Spectrum to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'Visible Spectrum to Workspace', ...
    'qdVisibleSpectrumSim',[850 35 1060 70]);
add_line(modelName,'Visible PL Spectrum Synthesis/1', ...
    'Visible Spectrum to Workspace/1','autorouting','on');
localAddWorkspaceSink(modelName,'CCD Measurements to Workspace', ...
    'qdCCDMeasurementSim',[985 330 1200 365]);
add_line(modelName,'CCD Readout/1','CCD Measurements to Workspace/1', ...
    'autorouting','on');
localAddWorkspaceSink(modelName,'Reconstructed Spectrum to Workspace', ...
    'qdReconstructedSpectrumSim',[1325 205 1555 240]);
add_line(modelName,'Nonnegative Spectral Reconstruction/1', ...
    'Reconstructed Spectrum to Workspace/1','autorouting','on');

Simulink.Annotation(modelName,sprintf([ ...
    'QD SWIR UPCONVERSION SPECTROMETER\n' ...
    'SWIR spectrum -> bias-tuned PbS CQD photodiode -> powered CdSe visible QLED -> CCD -> reconstruction\n' ...
    'Default response/efficiency is synthetic. Supply a measured end-to-end matrix for hardware prediction.']));
set_param(modelName,'ZoomFactor','FitSystem');
% Validate a staged artifact before replacing any previously working model.
save_system(modelName,stagingFile);
set_param(modelName,'SimulationCommand','update');
save_system(modelName,stagingFile);
close_system(modelName,0);
movefile(stagingFile,modelFile,'f');
end

function command = localInitCommand(initializer)
command = [ ...
    'qdPackageRoot=fileparts(fileparts(get_param(bdroot,''FileName'')));' ...
    'addpath(qdPackageRoot);setupQDVoltageSelectedDualConverter();' ...
    initializer '(false);clear qdPackageRoot;'];
end

function localAddWorkspaceSink(modelName,blockName,variableName,position)
add_block('simulink/Sinks/To Workspace',[modelName '/' blockName], ...
    'VariableName',variableName, ...
    'SaveFormat','Structure With Time', ...
    'MaxDataPoints','inf','Position',position);
end
