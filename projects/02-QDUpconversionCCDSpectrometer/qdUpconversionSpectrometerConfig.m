function config = qdUpconversionSpectrometerConfig(varargin)
%QDUPCONVERSIONSPECTROMETERCONFIG Configuration for the QD-CCD spectrometer.
%   CONFIG = QDUPCONVERSIONSPECTROMETERCONFIG creates a deterministic
%   12-pixel, five-bias computational spectrometer for 1.2-1.7 um input
%   light. Small-bandgap PbS dots define the input sensitizer centers and
%   CdSe/ZnS dots define the visible PL centers. Device-level upconversion
%   efficiency and bias tuning remain explicit calibration parameters.

%   The default is a physically constrained synthetic design, not a claim
%   of an experimentally calibrated NIR-to-visible conversion efficiency.

%   Common name-value options:
%     InputWavelength_nm             spectral reconstruction grid
%     VisibleWavelength_nm           visible-emission grid
%     SensitizerPixelCount           number of spatial converter pixels
%     BiasVoltages_V                 sequential response-tuning biases
%     InputResponseFWHM_nm           engineered input response width
%     BiasShiftRange_nm              center shift from min to max bias
%     PeakExternalPhotonEfficiency   emitted/incident photon ratio at peak
%     ConversionMechanism            electrically_assisted or multiphoton
%     ExposureTime_s                 exposure per bias state
%     ReconstructionRegularization   first-difference Tikhonov weight

%   Input spectra are photon counts PER CONVERTER PIXEL PER EXPOSURE and
%   PER WAVELENGTH BIN. Bias states are acquired sequentially.

%   See also QDBUILDSPECTRALRESPONSE, SIMULATEQDUPCONVERSIONCCD.


hc_eVnm = 1239.8419843320026;
scalarPositive = @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>0;
unitInterval = @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0&&x<=1;
vectorIncreasing = @(x)isnumeric(x)&&isvector(x)&&isreal(x)&& ...
    all(isfinite(x(:)))&&numel(x)>=3&&all(diff(x(:))>0);

parser = inputParser;
parser.FunctionName = 'qdUpconversionSpectrometerConfig';
addParameter(parser,'InputWavelength_nm',linspace(1200,1700,36).', ...
    vectorIncreasing);
addParameter(parser,'VisibleWavelength_nm',(420:2:720).',vectorIncreasing);
addParameter(parser,'SensitizerPixelCount',12, ...
    @(x)scalarPositive(x)&&x==fix(x)&&x>=4&&x<=64);
addParameter(parser,'BiasVoltages_V',linspace(0,0.68,5).',vectorIncreasing);
addParameter(parser,'InputResponseFWHM_nm',30,scalarPositive);
addParameter(parser,'BiasShiftRange_nm',35, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'PeakExternalPhotonEfficiency',0.010,unitInterval);
addParameter(parser,'ConversionMechanism','electrically_assisted', ...
    @(x)(ischar(x)||(isstring(x)&&isscalar(x)))&& ...
    any(strcmpi(char(x),{'electrically_assisted','multiphoton'})));
addParameter(parser,'OpticalTransmission',0.78,unitInterval);
addParameter(parser,'CCDQuantumEfficiencyPeak',0.88,unitInterval);
addParameter(parser,'CCDFillFactor',0.92,unitInterval);
addParameter(parser,'CCDReadNoiseElectronsRMS',1.5, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'CCDDarkCurrent_ePerSecond',0.20, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'CCDFullWellElectrons',8e4,scalarPositive);
addParameter(parser,'ExposureTime_s',0.020,scalarPositive);
addParameter(parser,'ReconstructionRegularization',0.010, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x>=0);
addParameter(parser,'ReconstructionMaxIterations',3000, ...
    @(x)scalarPositive(x)&&x==fix(x));
addParameter(parser,'RandomSeed',314159, ...
    @(x)isnumeric(x)&&isscalar(x)&&isreal(x)&&isfinite(x)&&x==fix(x)&&x>=0);
parse(parser,varargin{:});
options = parser.Results;

inputWavelength_nm = options.InputWavelength_nm(:);
visibleWavelength_nm = options.VisibleWavelength_nm(:);
biasVoltages_V = options.BiasVoltages_V(:);
pixelCount = options.SensitizerPixelCount;
biasCount = numel(biasVoltages_V);

% Keep the untuned centers just inside the requested grid so the extrema
% remain covered after the symmetric bias shift.
edgeInset_nm = min(0.45*options.InputResponseFWHM_nm, ...
    0.12*(inputWavelength_nm(end)-inputWavelength_nm(1)));
targetSensitizerCenter_nm = linspace(inputWavelength_nm(1)+edgeInset_nm, ...
    inputWavelength_nm(end)-edgeInset_nm,pixelCount).';

% Invert the published PbS first-exciton relation used by material ID 3:
% Eabs = 0.410 + 1/(0.0252*d^2 + 0.283*d), d in nm.
targetEnergy_eV = hc_eVnm./targetSensitizerCenter_nm;
if any(targetEnergy_eV <= 0.410)
    error('VirtualQD:SpectrometerBand', ...
        'The PbS calibration requires input photon energy above 0.410 eV.');
end
quadraticA = 0.0252;
quadraticB = 0.283;
inverseTerm = 1./(targetEnergy_eV-0.410);
sensitizerDiameter_nm = (-quadraticB+sqrt(quadraticB^2+ ...
    4*quadraticA*inverseTerm))/(2*quadraticA);
if any(sensitizerDiameter_nm < 3.9 | sensitizerDiameter_nm > 13.3)
    error('VirtualQD:SpectrometerBand', ...
        ['Requested input grid requires PbS diameters outside the ' ...
        'published 3.9-13.3 nm absorption calibration.']);
end

sensitizerCenter_nm = zeros(pixelCount,1);
sensitizerOpticalInScope = false(pixelCount,1);
sensitizerFlags = zeros(pixelCount,1,'uint32');
for pixelIndex = 1:pixelCount
    dotInput = qdCalibratedMaterialInputs(3,sensitizerDiameter_nm(pixelIndex));
    dotResult = simulateQD(dotInput,'Duration_ns',0,'ReturnTrace',false);
    sensitizerCenter_nm(pixelIndex) = hc_eVnm/dotResult.absorptionEnergy_eV;
    sensitizerOpticalInScope(pixelIndex) = ...
        dotResult.calibration.opticalInScope;
    sensitizerFlags(pixelIndex) = uint32(round(dotResult.validityFlags));
end

% The existing finite-barrier material-1 path supplies the visible-emitter
% energies. Radii are kept in its unflagged strong-confinement envelope.
emitterRadius_nm = linspace(1.8,4.0,pixelCount).';
emitterCenter_nm = zeros(pixelCount,1);
emitterFWHM_nm = zeros(pixelCount,1);
emitterFlags = zeros(pixelCount,1,'uint32');
for pixelIndex = 1:pixelCount
    dotInput = qdDefaultInputs();
    dotInput.radius_nm = emitterRadius_nm(pixelIndex);
    dotInput.pumpIntensity_Wcm2 = 0;
    dotResult = simulateQD(dotInput,'Duration_ns',0,'ReturnTrace',false);
    emitterCenter_nm(pixelIndex) = dotResult.emissionWavelength_nm;
    emitterFWHM_nm(pixelIndex) = dotResult.spectrum.plFWHM_eV* ...
        emitterCenter_nm(pixelIndex)^2/hc_eVnm;
    emitterFlags(pixelIndex) = uint32(round(dotResult.validityFlags));
end

config = struct();
config.schemaVersion = '2.0.0';
config.systemName = 'QD Upconversion CCD Computational Spectrometer';
config.conversionMechanism = lower(char(options.ConversionMechanism));
if strcmp(config.conversionMechanism,'electrically_assisted')
    config.conversionDescription = ['bias-tuned PbS CQD photodiode drives a ' ...
        'CdSe/ZnS visible QD emitter; external bias supplies the anti-Stokes energy'];
else
    config.conversionDescription = ['sensitized multiphoton PbS-to-CdSe/ZnS ' ...
        'upconversion; photon yield is valid only at its stated irradiance'];
end
config.inputDefinition = ['photons per input-wavelength bin, per converter ' ...
    'pixel, per bias-state exposure'];
config.inputWavelength_nm = inputWavelength_nm;
config.visibleWavelength_nm = visibleWavelength_nm;
config.biasVoltages_V = biasVoltages_V;
config.pixelCount = pixelCount;
config.biasCount = biasCount;
config.measurementCount = pixelCount*biasCount;
config.sensitizer = struct( ...
    'materialID',3, ...
    'material','PbS small-bandgap CQD', ...
    'diameter_nm',sensitizerDiameter_nm, ...
    'absorptionCenter_nm',sensitizerCenter_nm, ...
    'opticalInScope',sensitizerOpticalInScope, ...
    'coreValidityFlags',sensitizerFlags);
config.emitter = struct( ...
    'materialID',1, ...
    'material','CdSe/ZnS visible-emitting quantum dot', ...
    'radius_nm',emitterRadius_nm, ...
    'plCenter_nm',emitterCenter_nm, ...
    'plFWHM_nm',emitterFWHM_nm, ...
    'coreValidityFlags',emitterFlags);
config.device = struct( ...
    'inputResponseFWHM_nm',options.InputResponseFWHM_nm, ...
    'biasShiftRange_nm',options.BiasShiftRange_nm, ...
    'peakExternalPhotonEfficiency',options.PeakExternalPhotonEfficiency, ...
    'opticalTransmission',options.OpticalTransmission, ...
    'operatingPointMeaning',['efficiency is the emitted-visible/incident-' ...
    'NIR photon ratio at the configured irradiance and exposure']);
config.ccd = struct( ...
    'quantumEfficiencyPeak',options.CCDQuantumEfficiencyPeak, ...
    'fillFactor',options.CCDFillFactor, ...
    'readNoiseElectronsRMS',options.CCDReadNoiseElectronsRMS, ...
    'darkCurrent_ePerSecond',options.CCDDarkCurrent_ePerSecond, ...
    'fullWellElectrons',options.CCDFullWellElectrons, ...
    'exposureTime_s',options.ExposureTime_s);
config.reconstruction = struct( ...
    'method','nonnegative projected-FISTA Tikhonov', ...
    'regularization',options.ReconstructionRegularization, ...
    'maxIterations',options.ReconstructionMaxIterations);
config.randomSeed = options.RandomSeed;
config.measuredSystemResponse = [];
config.measuredDarkElectrons = [];
config.calibration = struct( ...
    'mode','physics-constrained synthetic response family', ...
    'label','UNMEASURED DEFAULT - replace with device calibration', ...
    'absoluteEfficiencyMeasured',false, ...
    'responseMatrixMeasured',false);
config.validity = struct( ...
    'sensitizerOpticalCalibrationCoverage',mean(sensitizerOpticalInScope), ...
    'allEmitterCoreRunsUnflagged',all(emitterFlags==0), ...
    'quantitativeHardwarePrediction',false, ...
    'requiresExternalElectricalPower', ...
        strcmp(config.conversionMechanism,'electrically_assisted'), ...
    'reason',['NIR-to-visible transfer efficiency and bias response are ' ...
    'synthetic until a measured response matrix is supplied.']);
end
