function report = validateCalibratedCdSePreset()
%VALIDATECALIBRATEDCDSEPRESET Quantify the scoped CdSe accuracy preset.
%   This is a calibration-consistency check against three published
%   room-temperature first-exciton sizing equations. It is deliberately not
%   described as independent validation because those same equations were
%   used to choose the effective material-5 parameters.

rootFolder = fileparts(mfilename('fullpath'));
diameter_nm = (3:0.25:8).';
reference = qdCdSeEmpiricalReferences(diameter_nm);
nPoints = numel(diameter_nm);
modelEnergy_eV = zeros(nPoints,1);
modelWavelength_nm = zeros(nPoints,1);
plEnergy_eV = zeros(nPoints,1);
modelRadiativeLifetime_ns = zeros(nPoints,1);
donegaRadiativeLifetime_ns = zeros(nPoints,1);
validityFlags = zeros(nPoints,1);

for k = 1:nPoints
    inputs = qdAccurateCdSeInputs(diameter_nm(k)/2);
    result = simulateQD(inputs,'Duration_ns',0);
    modelEnergy_eV(k) = result.absorptionEnergy_eV;
    modelWavelength_nm(k) = 1239.841984332/result.absorptionEnergy_eV;
    plEnergy_eV(k) = result.plEnergy_eV;
    modelRadiativeLifetime_ns(k) = 1e9/result.radiativeRate_Hz;
    donegaRadiativeLifetime_ns(k) = 1/(-0.1151+0.0753*result.plEnergy_eV);
    validityFlags(k) = result.validityFlags;
end

meanWavelength_nm = 1239.841984332./reference.ReferenceMeanEnergy_eV;
residualMean_eV = modelEnergy_eV-reference.ReferenceMeanEnergy_eV;
residualYu_eV = modelEnergy_eV-reference.YuEnergy_eV;
residualJasieniak_eV = modelEnergy_eV-reference.JasieniakEnergy_eV;
residualDonega_eV = modelEnergy_eV-reference.DonegaEnergy_eV;
insideSourceRange = modelEnergy_eV >= reference.ReferenceMinEnergy_eV & ...
    modelEnergy_eV <= reference.ReferenceMaxEnergy_eV;

comparison = table(diameter_nm,diameter_nm/2,modelEnergy_eV, ...
    reference.ReferenceMeanEnergy_eV,residualMean_eV, ...
    reference.YuEnergy_eV,residualYu_eV, ...
    reference.JasieniakEnergy_eV,residualJasieniak_eV, ...
    reference.DonegaEnergy_eV,residualDonega_eV, ...
    reference.ReferenceMinEnergy_eV,reference.ReferenceMaxEnergy_eV, ...
    reference.InterCurveSpread_eV,insideSourceRange, ...
    modelWavelength_nm,meanWavelength_nm,plEnergy_eV, ...
    modelRadiativeLifetime_ns,donegaRadiativeLifetime_ns,validityFlags, ...
    'VariableNames',{'Diameter_nm','Radius_nm','ModelAbsorptionEnergy_eV', ...
    'ThreeCurveMeanEnergy_eV','ResidualVsMean_eV','YuEnergy_eV', ...
    'ResidualVsYu_eV','JasieniakEnergy_eV','ResidualVsJasieniak_eV', ...
    'DonegaEnergy_eV','ResidualVsDonega_eV','SourceMinEnergy_eV', ...
    'SourceMaxEnergy_eV','InterCurveSpread_eV','InsideSourceRange', ...
    'ModelAbsorptionWavelength_nm','MeanReferenceWavelength_nm', ...
    'ModelPLEnergy_eV','ModelRadiativeLifetime_ns', ...
    'DonegaRadiativeLifetime_ns','ValidityFlags'});

report = struct();
report.scope = ['Material 5; bare CdSe core; diameter 3-8 nm; 300 K; ' ...
    'zero electric field and strain; no shell; environment dielectric 2.25'];
report.observable = 'first-exciton absorption energy';
report.comparison = comparison;
report.vsThreeCurveMean = localMetrics(modelEnergy_eV, ...
    reference.ReferenceMeanEnergy_eV);
report.vsYu2003 = localMetrics(modelEnergy_eV,reference.YuEnergy_eV);
report.vsJasieniak2009 = localMetrics(modelEnergy_eV, ...
    reference.JasieniakEnergy_eV);
report.vsDonegaKoole2009 = localMetrics(modelEnergy_eV, ...
    reference.DonegaEnergy_eV);
report.wavelengthVsThreeCurveMean = localMetrics(modelWavelength_nm, ...
    meanWavelength_nm);
report.fractionInsidePublishedSourceRange = mean(insideSourceRange);
report.referenceDisagreement = struct( ...
    'meanSpread_eV',mean(reference.InterCurveSpread_eV), ...
    'maximumSpread_eV',max(reference.InterCurveSpread_eV));
report.radiativeRateCalibration = struct( ...
    'lifetimeRMSE_ns',sqrt(mean((modelRadiativeLifetime_ns- ...
        donegaRadiativeLifetime_ns).^2)), ...
    'interpretation',['The empirical rate equation is used directly inside ' ...
        'the preset envelope, so this is an identity/calibration check, not ' ...
        'independent lifetime validation.']);
report.plValidated = false;
report.plNote = ['The source equations measure absorption, not PL. Supply a ' ...
    'sample-specific stokesShiftOverride_eV before interpreting lambda2.'];
report.independentHeldOutValidation = false;
report.interpretation = ['Residuals quantify agreement with the equations ' ...
    'used for calibration. Published-curve spread is a model-choice ' ...
    'diagnostic, not a statistical confidence interval.'];
report.sources = struct( ...
    'Yu2003','https://doi.org/10.1021/cm034081k', ...
    'Jasieniak2009','https://doi.org/10.1021/jp906827m', ...
    'DonegaKoole2009','https://doi.org/10.1021/jp811329r');
report.timestamp = char(datetime('now','TimeZone','local', ...
    'Format','yyyy-MM-dd HH:mm:ss Z'));

writetable(comparison,fullfile(rootFolder,'CALIBRATED_CDSE_COMPARISON.csv'), ...
    'WriteMode','overwrite');
save(fullfile(rootFolder,'CalibratedCdSeValidation.mat'),'report');
localWriteText(rootFolder,report);
localPlot(rootFolder,comparison,report);
end

function metrics = localMetrics(predicted,reference)
residual = predicted-reference;
metrics = struct('N',numel(residual),'Bias',mean(residual), ...
    'MAE',mean(abs(residual)),'RMSE',sqrt(mean(residual.^2)), ...
    'MaxAbsError',max(abs(residual)));
end

function localWriteText(rootFolder,report)
fileID = fopen(fullfile(rootFolder,'CALIBRATED_CDSE_VALIDATION.txt'),'w');
cleanup = onCleanup(@()fclose(fileID));
fprintf(fileID,'Virtual Quantum Dot Agent - Calibrated CdSe Preset\n');
fprintf(fileID,'Timestamp: %s\n',report.timestamp);
fprintf(fileID,'Scope: %s\n',report.scope);
fprintf(fileID,'Observable: %s\n\n',report.observable);
fprintf(fileID,'RMSE versus three-curve mean : %.6f eV\n', ...
    report.vsThreeCurveMean.RMSE);
fprintf(fileID,'RMSE versus Yu 2003          : %.6f eV\n', ...
    report.vsYu2003.RMSE);
fprintf(fileID,'RMSE versus Jasieniak 2009   : %.6f eV\n', ...
    report.vsJasieniak2009.RMSE);
fprintf(fileID,'RMSE versus Donega/Koole     : %.6f eV\n', ...
    report.vsDonegaKoole2009.RMSE);
fprintf(fileID,'Wavelength RMSE versus mean  : %.3f nm\n', ...
    report.wavelengthVsThreeCurveMean.RMSE);
fprintf(fileID,'Maximum absolute mean error  : %.6f eV\n', ...
    report.vsThreeCurveMean.MaxAbsError);
fprintf(fileID,'Inside published source span : %.1f %%\n', ...
    100*report.fractionInsidePublishedSourceRange);
fprintf(fileID,'Maximum source disagreement  : %.6f eV\n\n', ...
    report.referenceDisagreement.maximumSpread_eV);
fprintf(fileID,'Independent held-out validation: NO\n');
fprintf(fileID,'PL externally validated: NO\n');
fprintf(fileID,'%s\n%s\n',report.interpretation,report.plNote);
end

function localPlot(rootFolder,comparison,report)
figureHandle = figure('Visible','off','Color','w','Position',[100 100 1050 720]);
tiledlayout(2,1,'Padding','compact','TileSpacing','compact');
nexttile;
fill([comparison.Diameter_nm;flipud(comparison.Diameter_nm)], ...
    [comparison.SourceMinEnergy_eV;flipud(comparison.SourceMaxEnergy_eV)], ...
    [0.86 0.91 1.0],'EdgeColor','none','DisplayName','Published source range');
hold on;
plot(comparison.Diameter_nm,comparison.ThreeCurveMeanEnergy_eV,'k--', ...
    'LineWidth',1.5,'DisplayName','Three-curve mean');
plot(comparison.Diameter_nm,comparison.ModelAbsorptionEnergy_eV,'b-', ...
    'LineWidth',2.2,'DisplayName','Material 5 model');
xlabel('CdSe diameter (nm)'); ylabel('First-exciton energy (eV)');
title('Scoped CdSe absorption calibration'); grid on; legend('Location','best');
nexttile;
plot(comparison.Diameter_nm,1e3*comparison.ResidualVsMean_eV,'b-o', ...
    'LineWidth',1.5,'MarkerSize',3); hold on; yline(0,'k:');
xlabel('CdSe diameter (nm)'); ylabel('Model - mean (meV)'); grid on;
title(sprintf('Calibration RMSE %.2f meV; no held-out validation', ...
    1e3*report.vsThreeCurveMean.RMSE));
exportgraphics(figureHandle, ...
    fullfile(rootFolder,'CalibratedCdSeValidation.png'),'Resolution',180);
close(figureHandle);
end
