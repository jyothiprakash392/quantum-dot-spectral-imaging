function modelFile = buildVirtualQuantumDotAgent(forceRebuild)
%BUILDVIRTUALQUANTUMDOTAGENT Create the runnable Simulink digital twin.
%   BUILDVIRTUALQUANTUMDOTAGENT(true) rebuilds the generated model.

if nargin < 1
    forceRebuild = false;
end

rootFolder = fileparts(mfilename('fullpath'));
addpath(rootFolder);
initVirtualQuantumDotAgent();
modelName = 'VirtualQuantumDotAgent';
modelFile = fullfile(rootFolder,[modelName '.slx']);

if bdIsLoaded(modelName)
    close_system(modelName,0);
end
if isfile(modelFile) && ~forceRebuild
    load_system(modelFile);
    if usejava('desktop')
        open_system(modelName);
    end
    return
end
if isfile(modelFile)
    delete(modelFile);
end

new_system(modelName);
set_param(modelName, ...
    'SolverType','Fixed-step', ...
    'Solver','FixedStepDiscrete', ...
    'FixedStep','1e-11', ...
    'StartTime','0', ...
    'StopTime','50e-9', ...
    'SignalLogging','on', ...
    'SignalLoggingName','logsout', ...
    'ReturnWorkspaceOutputs','on', ...
    'InitFcn','qdEnsureWorkspace;', ...
    'ModelVersionFormat','1.2', ...
    'Description','Virtual Quantum Dot Agent package model 1.5.1', ...
    'ModelBrowserVisibility','off');

inputNames = qdInputNames();
inputBlockNames = { ...
    'Radius_nm','Temperature_K','Field_kVcm','HydrostaticStrain_pct', ...
    'Pump_Wcm2','PumpPhotonEnergy_eV','Shell_nm','TrapDensity_cm2', ...
    'EnvironmentEpsilon','ElectronBarrier_eV','HoleBarrier_eV', ...
    'TargetEmission_eV','MaterialID','StokesShiftOverride_eV'};
photonInputNames = {'incidentPhotonCount','inputWavelength_nm', ...
    'beamArea_um2','pumpDuration_ns'};
photonBlockNames = {'IncidentPhotonCount','Lambda1_nm', ...
    'BeamArea_um2','PumpDuration_ns'};

% Named constants make every public input immediately editable.
for k = 1:numel(inputNames)
    row = mod(k-1,7);
    column = floor((k-1)/7);
    x = 30+column*230;
    y = 55+row*70;
    blockPath = [modelName '/' inputBlockNames{k}];
    add_block('simulink/Sources/Constant',blockPath, ...
        'Value',['qdInput.' inputNames{k}], ...
        'SampleTime','QD_SAMPLE_TIME_S', ...
        'Position',[x y x+175 y+34]);
end

% User-facing photon-count/lambda1 inputs. A zero count selects legacy mode.
for k = 1:numel(photonInputNames)
    y = 565+(k-1)*70;
    blockPath = [modelName '/' photonBlockNames{k}];
    add_block('simulink/Sources/Constant',blockPath, ...
        'Value',['qdInput.' photonInputNames{k}], ...
        'SampleTime','QD_SAMPLE_TIME_S', ...
        'Position',[30 y 220 y+34]);
end

adapterPath = [modelName '/Photon Count and Lambda1 Adapter'];
localAddPhotonAdapter(adapterPath);
set_param(adapterPath,'Position',[290 555 470 825]);
add_line(modelName,'Pump_Wcm2/1','Photon Count and Lambda1 Adapter/1', ...
    'autorouting','on');
add_line(modelName,'PumpPhotonEnergy_eV/1','Photon Count and Lambda1 Adapter/2', ...
    'autorouting','on');
for k = 1:numel(photonBlockNames)
    add_line(modelName,[photonBlockNames{k} '/1'], ...
        ['Photon Count and Lambda1 Adapter/' num2str(k+2)],'autorouting','on');
end

muxPath = [modelName '/QD Input Vector'];
add_block('simulink/Signal Routing/Mux',muxPath, ...
    'Inputs',num2str(numel(inputNames)), ...
    'Position',[500 55 506 505]);
for k = 1:numel(inputNames)
    if k ~= 5 && k ~= 6
        add_line(modelName,[inputBlockNames{k} '/1'], ...
            ['QD Input Vector/' num2str(k)],'autorouting','on');
    end
end
add_line(modelName,'Photon Count and Lambda1 Adapter/1','QD Input Vector/5', ...
    'autorouting','on');
add_line(modelName,'Photon Count and Lambda1 Adapter/2','QD Input Vector/6', ...
    'autorouting','on');

% Reusable masked virtual-dot subsystem.
subsystemPath = [modelName '/Virtual Quantum Dot Agent'];
add_block('simulink/Ports & Subsystems/Subsystem',subsystemPath, ...
    'Position',[570 160 815 385]);
Simulink.SubSystem.deleteContents(subsystemPath);
add_block('simulink/Ports & Subsystems/In1',[subsystemPath '/QD Inputs'], ...
    'PortDimensions','14', ...
    'Position',[35 98 65 112]);
functionPath = [subsystemPath '/Finite Barrier Physics and Agent'];
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function',functionPath, ...
    'FunctionName','qdAgentSFunction', ...
    'Position',[135 72 340 138]);
add_block('simulink/Ports & Subsystems/Out1',[subsystemPath '/QD Outputs'], ...
    'Position',[415 98 445 112]);

add_line(subsystemPath,'QD Inputs/1','Finite Barrier Physics and Agent/1','autorouting','on');
add_line(subsystemPath,'Finite Barrier Physics and Agent/1','QD Outputs/1','autorouting','on');
Simulink.Annotation(subsystemPath, ...
    sprintf(['Finite spherical barriers + Coulomb + dielectric + Stark + strain\n' ...
    'Four states: p0, pX, pXX, pTrap | exact Markov exponential update']));

mask = Simulink.Mask.create(subsystemPath);
mask.Description = ['Effective-mass quantum-dot digital twin with ' ...
    'population dynamics and inverse radius recommendation.'];
mask.Display = sprintf([ ...
    'disp(''VIRTUAL QUANTUM DOT\\nPHYSICS + AGENT'');\n' ...
    'port_label(''input'',1,''14 inputs'');\n' ...
    'port_label(''output'',1,''40 outputs'');']);

add_line(modelName,'QD Input Vector/1','Virtual Quantum Dot Agent/1','autorouting','on');

demuxPath = [modelName '/Named Output Split'];
add_block('simulink/Signal Routing/Demux',demuxPath, ...
    'Outputs','40', ...
    'Position',[870 25 876 760]);
add_line(modelName,'Virtual Quantum Dot Agent/1','Named Output Split/1','autorouting','on');

workspacePath = [modelName '/All Outputs to Workspace'];
add_block('simulink/Sinks/To Workspace',workspacePath, ...
    'VariableName','qdOutput', ...
    'SaveFormat','Structure With Time', ...
    'MaxDataPoints','inf', ...
    'Position',[875 790 1045 830]);
add_line(modelName,'Virtual Quantum Dot Agent/1','All Outputs to Workspace/1','autorouting','on');

displayIndices = [8 9 10 21 22 23 25 26 27 28 29 30 31];
displayNames = { ...
    'Absorption Energy eV','PL Energy eV','Lambda2 Emission Wavelength nm', ...
    'Exciton Probability','Biexciton Probability','Trap Probability', ...
    'PL Photon Rate Hz','Internal Quantum Yield','Lifetime ns', ...
    'Suggested Radius nm','Target Error eV','Model Confidence','Validity Flags'};
for k = 1:numel(displayIndices)
    column = floor((k-1)/7);
    row = mod(k-1,7);
    x = 990+column*245;
    y = 35+row*100;
    safeName = regexprep(displayNames{k},'[^A-Za-z0-9]','_');
    displayPath = [modelName '/' safeName];
    add_block('simulink/Sinks/Display',displayPath, ...
        'Position',[x y x+190 y+50], ...
        'Format','short');
    add_line(modelName,['Named Output Split/' num2str(displayIndices(k))], ...
        [safeName '/1'],'autorouting','on');
end

populationMux = [modelName '/Population Vector'];
add_block('simulink/Signal Routing/Mux',populationMux, ...
    'Inputs','4','Position',[1000 760 1006 845]);
for k = 1:4
    add_line(modelName,['Named Output Split/' num2str(19+k)], ...
        ['Population Vector/' num2str(k)],'autorouting','on');
end
scopePath = [modelName '/Population Scope'];
add_block('simulink/Sinks/Scope',scopePath, ...
    'Position',[1090 770 1160 835]);
add_line(modelName,'Population Vector/1','Population Scope/1','autorouting','on');

% Delivered incident and expected per-dot counts are kept separate from the
% stable 40-output vector.
rateMuxPath = [modelName '/Photon Rate Vector'];
add_block('simulink/Signal Routing/Mux',rateMuxPath, ...
    'Inputs','4','Position',[900 865 906 980]);
add_line(modelName,'Photon Count and Lambda1 Adapter/3', ...
    'Photon Rate Vector/1','autorouting','on');
add_line(modelName,'Named Output Split/38','Photon Rate Vector/2','autorouting','on');
add_line(modelName,'Named Output Split/25','Photon Rate Vector/3','autorouting','on');
add_line(modelName,'Named Output Split/39','Photon Rate Vector/4','autorouting','on');

accumulatorPath = [modelName '/Photon Count Accumulator'];
localAddPhotonAccumulator(accumulatorPath);
set_param(accumulatorPath,'Position',[990 875 1185 970]);
add_line(modelName,'Photon Rate Vector/1','Photon Count Accumulator/1', ...
    'autorouting','on');

countMuxPath = [modelName '/Photon Count Vector'];
add_block('simulink/Signal Routing/Mux',countMuxPath, ...
    'Inputs','1','Position',[1235 865 1241 980]);
add_line(modelName,'Photon Count Accumulator/1','Photon Count Vector/1', ...
    'autorouting','on');

countWorkspacePath = [modelName '/Photon Counts to Workspace'];
add_block('simulink/Sinks/To Workspace',countWorkspacePath, ...
    'VariableName','qdPhotonCounts', ...
    'SaveFormat','Structure With Time', ...
    'MaxDataPoints','inf', ...
    'Position',[1300 900 1490 940]);
add_line(modelName,'Photon Count Vector/1','Photon Counts to Workspace/1', ...
    'autorouting','on');

Simulink.Annotation(modelName,sprintf([ ...
    'VIRTUAL QUANTUM-DOT AGENT v1.2  |  CdSe/ZnS mechanistic default\n' ...
    'Photon mode: set incidentPhotonCount > 0 plus lambda1, beam area and pump duration.\n' ...
    'Lambda2 is emissionWavelength_nm (output 10). Zero photon count preserves legacy pump inputs.\n' ...
    'The v1.2 core has 14 inputs and 40 outputs; qdPhotonCounts stores ' ...
    '[delivered incident, absorbed, emitted, trap emission].']));

set_param(modelName,'ZoomFactor','FitSystem');
save_system(modelName,modelFile);
set_param(modelName,'SimulationCommand','update');
save_system(modelName,modelFile);
if usejava('desktop')
    open_system(modelName);
end
end

function localAddPhotonAdapter(subsystemPath)
% Map N, lambda1, area, and pulse duration onto the stable pump interface.
add_block('simulink/Ports & Subsystems/Subsystem',subsystemPath);
Simulink.SubSystem.deleteContents(subsystemPath);

inNames = {'Legacy Intensity','Legacy Energy','Photon Count', ...
    'Lambda1 nm','Beam Area um2','Pump Duration ns'};
for k = 1:numel(inNames)
    y = 20+(k-1)*48;
    add_block('simulink/Ports & Subsystems/In1', ...
        [subsystemPath '/' inNames{k}], ...
        'Port',num2str(k),'Position',[20 y 50 y+14]);
end

add_block('simulink/Signal Routing/Mux',[subsystemPath '/Photon Inputs'], ...
    'Inputs','4','Position',[125 105 131 245]);
for k = 1:4
    add_line(subsystemPath,[inNames{k+2} '/1'], ...
        ['Photon Inputs/' num2str(k)],'autorouting','on');
end

add_block('simulink/User-Defined Functions/Fcn', ...
    [subsystemPath '/Count to Intensity'], ...
    'Expr',['19.8644585714893*u(1)*(u(1)>0)/' ...
        '((abs(u(2))+(u(2)==0))*(abs(u(3))+(u(3)==0))*' ...
        '(abs(u(4))+(u(4)==0)))'], ...
    'Position',[185 108 430 138]);
add_line(subsystemPath,'Photon Inputs/1','Count to Intensity/1','autorouting','on');

add_block('simulink/User-Defined Functions/Fcn', ...
    [subsystemPath '/Lambda1 to Energy'], ...
    'Expr','1239.841984332/(abs(u(1))+(u(1)==0))', ...
    'Position',[185 165 430 195]);
add_line(subsystemPath,'Lambda1 nm/1','Lambda1 to Energy/1','autorouting','on');

add_block('simulink/Math Operations/Gain',[subsystemPath '/Duration to Seconds'], ...
    'Gain','1e-9','Position',[180 245 280 275]);
add_line(subsystemPath,'Pump Duration ns/1','Duration to Seconds/1', ...
    'autorouting','on');
add_block('simulink/Sources/Clock',[subsystemPath '/Clock'], ...
    'Position',[185 300 215 320]);
add_block('simulink/Math Operations/Sum', ...
    [subsystemPath '/Remaining Pulse Duration'], ...
    'Inputs','+-','Position',[325 250 360 300]);
add_line(subsystemPath,'Duration to Seconds/1', ...
    'Remaining Pulse Duration/1','autorouting','on');
add_line(subsystemPath,'Clock/1','Remaining Pulse Duration/2', ...
    'autorouting','on');
add_block('simulink/Math Operations/Gain', ...
    [subsystemPath '/Remaining Duration to Duty'], ...
    'Gain','1/QD_SAMPLE_TIME_S','Position',[390 260 470 290]);
add_line(subsystemPath,'Remaining Pulse Duration/1', ...
    'Remaining Duration to Duty/1','autorouting','on');
add_block('simulink/Discontinuities/Saturation', ...
    [subsystemPath '/Pulse Interval Duty'], ...
    'LowerLimit','0','UpperLimit','1','Position',[505 255 555 295]);
add_line(subsystemPath,'Remaining Duration to Duty/1', ...
    'Pulse Interval Duty/1','autorouting','on');

add_block('simulink/Math Operations/Product',[subsystemPath '/Pulse Gate'], ...
    'Inputs','**','Position',[470 108 500 143]);
add_line(subsystemPath,'Count to Intensity/1','Pulse Gate/1','autorouting','on');
add_line(subsystemPath,'Pulse Interval Duty/1','Pulse Gate/2','autorouting','on');

% Integrating this gated rate yields the count actually delivered before the
% simulation stop time, rather than always reporting the requested pulse count.
add_block('simulink/User-Defined Functions/Fcn', ...
    [subsystemPath '/Count to Photon Rate'], ...
    'Expr','1e9*u(1)*(u(1)>0)/(abs(u(4))+(u(4)==0))', ...
    'Position',[185 205 430 235]);
add_line(subsystemPath,'Photon Inputs/1','Count to Photon Rate/1', ...
    'autorouting','on');
add_block('simulink/Math Operations/Product', ...
    [subsystemPath '/Delivered Photon Rate Gate'], ...
    'Inputs','**','Position',[470 205 500 240]);
add_line(subsystemPath,'Count to Photon Rate/1', ...
    'Delivered Photon Rate Gate/1','autorouting','on');
add_line(subsystemPath,'Pulse Interval Duty/1', ...
    'Delivered Photon Rate Gate/2','autorouting','on');

add_block('simulink/Signal Routing/Switch',[subsystemPath '/Select Intensity'], ...
    'Criteria','u2 > Threshold','Threshold','0', ...
    'Position',[550 55 600 125]);
add_line(subsystemPath,'Pulse Gate/1','Select Intensity/1','autorouting','on');
add_line(subsystemPath,'Photon Count/1','Select Intensity/2','autorouting','on');
add_line(subsystemPath,'Legacy Intensity/1','Select Intensity/3','autorouting','on');

add_block('simulink/Signal Routing/Switch',[subsystemPath '/Select Energy'], ...
    'Criteria','u2 > Threshold','Threshold','0', ...
    'Position',[550 165 600 235]);
add_line(subsystemPath,'Lambda1 to Energy/1','Select Energy/1','autorouting','on');
add_line(subsystemPath,'Photon Count/1','Select Energy/2','autorouting','on');
add_line(subsystemPath,'Legacy Energy/1','Select Energy/3','autorouting','on');

add_block('simulink/Ports & Subsystems/Out1', ...
    [subsystemPath '/Effective Intensity'], ...
    'Port','1','Position',[660 78 690 92]);
add_block('simulink/Ports & Subsystems/Out1', ...
    [subsystemPath '/Effective Energy'], ...
    'Port','2','Position',[660 188 690 202]);
add_block('simulink/Ports & Subsystems/Out1', ...
    [subsystemPath '/Delivered Photon Rate'], ...
    'Port','3','Position',[660 238 690 252]);
add_line(subsystemPath,'Select Intensity/1','Effective Intensity/1', ...
    'autorouting','on');
add_line(subsystemPath,'Select Energy/1','Effective Energy/1', ...
    'autorouting','on');
add_line(subsystemPath,'Delivered Photon Rate Gate/1', ...
    'Delivered Photon Rate/1','autorouting','on');

Simulink.Annotation(subsystemPath,sprintf([ ...
    'N photons in a uniform square pulse\n' ...
    'E1 = 1239.841984332 / lambda1\n' ...
    'I = 19.8644585714893 N/(lambda1 A duration) W/cm^2\n' ...
    'Each 10 ps step uses its exact fractional overlap with the pulse.\n' ...
    'Photon Count = 0 selects the legacy pump inputs.']));
mask = Simulink.Mask.create(subsystemPath);
mask.Description = ['Backward-compatible photon count and wavelength ' ...
    'adapter for the 14-input quantum-dot core.'];
mask.Display = sprintf([ ...
    'disp(''PHOTON INPUT: N + LAMBDA1'');\n' ...
    'port_label(''output'',1,''intensity'');\n' ...
    'port_label(''output'',2,''energy'');\n' ...
    'port_label(''output'',3,''delivered rate'');']);
end

function localAddPhotonAccumulator(subsystemPath)
% Integrate delivered incident and per-dot rates once per 10 ps model step.
add_block('simulink/Ports & Subsystems/Subsystem',subsystemPath);
Simulink.SubSystem.deleteContents(subsystemPath);
add_block('simulink/Ports & Subsystems/In1',[subsystemPath '/Rates'], ...
    'Position',[25 93 55 107]);
add_block('simulink/Signal Routing/Demux',[subsystemPath '/Split Rates'], ...
    'Outputs','4','Position',[105 35 111 215]);
add_line(subsystemPath,'Rates/1','Split Rates/1','autorouting','on');

integratorNames = {'Delivered Incident Count','Absorbed Count', ...
    'Emitted Count','Trap Emission Count'};
for k = 1:4
    y = 35+(k-1)*60;
    add_block('simulink/Discrete/Discrete-Time Integrator', ...
        [subsystemPath '/' integratorNames{k}], ...
        'IntegratorMethod','Forward Euler', ...
        'gainval','1', ...
        'InitialCondition','0', ...
        'SampleTime','QD_SAMPLE_TIME_S', ...
        'Position',[175 y 315 y+35]);
    add_line(subsystemPath,['Split Rates/' num2str(k)], ...
        [integratorNames{k} '/1'],'autorouting','on');
end
add_block('simulink/Signal Routing/Mux',[subsystemPath '/Counts'], ...
    'Inputs','4','Position',[370 35 376 230]);
for k = 1:4
    add_line(subsystemPath,[integratorNames{k} '/1'], ...
        ['Counts/' num2str(k)],'autorouting','on');
end
add_block('simulink/Ports & Subsystems/Out1',[subsystemPath '/Expected Counts'], ...
    'Position',[440 93 470 107]);
add_line(subsystemPath,'Counts/1','Expected Counts/1','autorouting','on');
Simulink.Annotation(subsystemPath, ...
    sprintf(['Integrated counts: delivered photons for the beam, then expected ' ...
    'fractional photons per dot for [absorption, total PL, trap emission].']));
end
