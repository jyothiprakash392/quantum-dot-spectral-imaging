function manifest = writeValidationManifest()
%WRITEVALIDATIONMANIFEST Record the exact tested package/model identity.

rootFolder = fileparts(mfilename('fullpath'));
core = load(fullfile(rootFolder,'QDValidationResults.mat'),'report');
empirical = load(fullfile(rootFolder,'RealWorldValidationTests.mat'),'report');
calibration = load(fullfile(rootFolder,'CalibratedCdSeValidation.mat'),'report');
multiMaterial = load(fullfile(rootFolder, ...
    'MultiMaterialCalibrationValidation.mat'),'report');
hybridBenchmark = load(fullfile(rootFolder,'QDHybridModelBenchmark.mat'),'report');
deployedHybrid = hybridBenchmark.report.kinetic.deployedModel;
hybridTests = load(fullfile(rootFolder,'QDHybridValidationTests.mat'),'report');
ensembleTests = load(fullfile(rootFolder,'QDEnsembleValidationTests.mat'), ...
    'report');

manifest = struct();
manifest.package = 'VirtualQuantumDotAgent';
manifest.modelVersion = '1.5.1';
manifest.matlabVersion = version;
manifest.generatedAt = char(datetime('now','TimeZone','local', ...
    'Format','yyyy-MM-dd''T''HH:mm:ssXXX'));
manifest.coreAndSimulinkTests = struct('passed',core.report.passed, ...
    'failed',core.report.failed,'timestamp',core.report.timestamp);
manifest.empiricalWorkflowTests = struct('passed',empirical.report.passed, ...
    'failed',empirical.report.failed,'timestamp',empirical.report.timestamp);
manifest.hybridModelTests = struct('passed',hybridTests.report.passed, ...
    'failed',hybridTests.report.failed,'timestamp',hybridTests.report.timestamp);
manifest.ensembleObservationTests = struct( ...
    'passed',ensembleTests.report.passed, ...
    'failed',ensembleTests.report.failed, ...
    'timestamp',ensembleTests.report.timestamp);
manifest.totalTestsPassed = core.report.passed+empirical.report.passed+ ...
    multiMaterial.report.passed+hybridTests.report.passed+ ...
    ensembleTests.report.passed;
manifest.totalTestsFailed = core.report.failed+empirical.report.failed+ ...
    multiMaterial.report.failed+hybridTests.report.failed+ ...
    ensembleTests.report.failed;
manifest.ensembleObservation = struct( ...
    'distribution','number-weighted lognormal or measured discrete radii', ...
    'lognormalFixture',ensembleTests.report.lognormalFixture, ...
    'detectorCountModel',['Poisson signal/dark expectations with optional ' ...
        'excess and Gaussian read-noise variance'], ...
    'independentDotApproximation',true, ...
    'pumpDepletionModeled',false, ...
    'formalConfidenceInterval',false);
manifest.calibratedCdSe = struct( ...
    'scope',calibration.report.scope, ...
    'observable',calibration.report.observable, ...
    'rmseVsThreeCurveMean_eV',calibration.report.vsThreeCurveMean.RMSE, ...
    'wavelengthRmseVsThreeCurveMean_nm', ...
        calibration.report.wavelengthVsThreeCurveMean.RMSE, ...
    'externalHeldOutValidation',false, ...
    'plValidated',false);
manifest.calibratedMaterials2Through4 = struct( ...
    'passed',multiMaterial.report.passed, ...
    'failed',multiMaterial.report.failed, ...
    'timestamp',multiMaterial.report.timestamp, ...
    'id2ReferenceRegressionMaxAbsError_eV', ...
        multiMaterial.report.id2.referenceRegressionMaxAbsError_eV, ...
    'id2ExternalInScopeEnergyRMSE_eV',NaN, ...
    'id2OutOfScopeInPZnSeAbsorptionSingleError_eV', ...
        multiMaterial.report.id2.outOfScopeInPZnSeAbsorptionSingleError_eV, ...
    'id2OutOfScopeInPZnSePLSingleError_eV', ...
        multiMaterial.report.id2.outOfScopeInPZnSePLSingleError_eV, ...
    'id3ReferenceRegressionMaxAbsError_eV', ...
        multiMaterial.report.id3.referenceRegressionMaxAbsError_eV, ...
    'id3ExternalInScopeEnergyRMSE_eV',NaN, ...
    'id3ThickShellPLHoldoutRMSE_eV', ...
        multiMaterial.report.id3.thickShellPLHoldoutRMSE_eV, ...
    'id3ThickShellOverlapHoldoutRMSE', ...
        multiMaterial.report.id3.thickShellOverlapHoldoutRMSE, ...
    'id3AugerWholeSeriesCVRMSE_ps', ...
        multiMaterial.report.id3.augerWholeSeriesCVRMSE_ps, ...
    'id3AugerGenericBaselineRMSE_ps', ...
        multiMaterial.report.id3.genericAugerBaselineRMSE_ps, ...
    'id4ExternalCrossSourceAbsorptionRMSE_eV', ...
        multiMaterial.report.id4.externalCrossSourceAbsorptionRMSE_eV, ...
    'id4ExternalCrossSourceAbsorptionBias_eV', ...
        multiMaterial.report.id4.externalCrossSourceAbsorptionBias_eV, ...
    'id4CrossProtocolPLAnchorRMSE_eV', ...
        multiMaterial.report.id4.crossProtocolPLAnchorRMSE_eV, ...
    'id4KineticMetrics',multiMaterial.report.id4.kineticMetrics);
manifest.physicsPlusML = struct( ...
    'randomSeed',hybridBenchmark.report.randomSeed, ...
    'opticalProtocol','Mondal-2019', ...
    'opticalSelectedModel',hybridBenchmark.report.optical.selectedModel, ...
    'opticalDevelopmentSizes',numel( ...
        hybridBenchmark.report.optical.developmentIndices), ...
    'opticalFrozenSizes',numel(hybridBenchmark.report.optical.holdoutIndices), ...
    'opticalDevelopmentLOOCVRMSE_eV', ...
        hybridBenchmark.report.optical.selectedInnerCVRMSE_eV, ...
    'opticalBaselineFrozenRMSE_eV', ...
        hybridBenchmark.report.optical.baselineHoldoutRMSE_eV, ...
    'opticalAdaptedFrozenRMSE_eV', ...
        hybridBenchmark.report.optical.hybridHoldoutRMSE_eV, ...
    'opticalAdaptedFrozenBias_eV', ...
        hybridBenchmark.report.optical.hybridHoldoutBias_eV, ...
    'opticalLearnedResidual_eV',-0.0667159090909091, ...
    'opticalProtocolSpecific',true, ...
    'plAdapted',false, ...
    'kineticModel',deployedHybrid.name, ...
    'kineticRidgeLambda',deployedHybrid.selectedLambda, ...
    'kineticDevelopmentCompositeRatio', ...
        deployedHybrid.selectedDevelopmentCompositeRatio, ...
    'kineticFrozenMetrics', ...
        deployedHybrid.frozenHoldoutMetrics, ...
    'kineticFrozenRadiativeLifetimeRMSE_ns', ...
        deployedHybrid.frozenRadiativeLifetimeRMSE_ns, ...
    'conditionalOnPLEnergy',true, ...
    'endToEndSizeToKineticsValidated',false);
manifest.sources = struct( ...
    'cdSe',calibration.report.sources, ...
    'inP','https://doi.org/10.1021/acs.nanolett.3c02630', ...
    'inPZnSeHoldout','https://doi.org/10.1021/acsphotonics.8b00615', ...
    'pbS','https://doi.org/10.1021/nn900863a', ...
    'pbSCdS','https://doi.org/10.1021/jp406774p', ...
    'pbSCdSAuger','https://doi.org/10.1021/acs.nanolett.6c00158', ...
    'pbSCdSThickShellHoldout','https://doi.org/10.1021/acsnano.0c05907', ...
    'csPbBr3Optics','https://doi.org/10.1021/jacs.7b05683', ...
    'csPbBr3ExternalOpticalComparison','https://doi.org/10.1039/C9SC01339C', ...
    'csPbBr3Kinetics','https://doi.org/10.1038/s41467-025-60848-5');
% Hash every top-level publication artifact while excluding this self-updating
% manifest, autosaves, caches, and editor metadata.
allowedExtensions = {'.m','.md','.slx','.csv','.txt','.mat','.png'};
entries = dir(rootFolder);
hashedFiles = cell(0,1);
for k = 1:numel(entries)
    if entries(k).isdir || startsWith(entries(k).name,'.') || ...
            strcmp(entries(k).name,'VALIDATION_MANIFEST.json')
        continue
    end
    [~,~,extension] = fileparts(entries(k).name);
    if any(strcmpi(extension,allowedExtensions))
        hashedFiles{end+1,1} = entries(k).name; %#ok<AGROW>
    end
end
hashedFiles = sort(hashedFiles);
manifest.hashedFileCount = numel(hashedFiles);
hashes = struct();
for k = 1:numel(hashedFiles)
    fieldName = matlab.lang.makeValidName(hashedFiles{k});
    hashes.(fieldName) = localSHA256(fullfile(rootFolder,hashedFiles{k}));
end
manifest.sha256 = hashes;

jsonText = jsonencode(manifest,'PrettyPrint',true);
fileID = fopen(fullfile(rootFolder,'VALIDATION_MANIFEST.json'),'w');
cleanup = onCleanup(@()fclose(fileID));
fprintf(fileID,'%s\n',jsonText);
end

function hash = localSHA256(fileName)
fileID = fopen(fileName,'rb');
if fileID < 0
    error('VirtualQD:ManifestFile','Cannot open %s.',fileName);
end
cleanup = onCleanup(@()fclose(fileID));
bytes = fread(fileID,inf,'*uint8');
digest = java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(bytes,'int8'));
hashBytes = typecast(digest.digest(),'uint8');
hash = lower(reshape(dec2hex(hashBytes,2).',1,[]));
end
